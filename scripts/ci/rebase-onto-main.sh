#!/usr/bin/env bash
# Rebase this run's commits onto the freshly fetched origin/main without ever dropping them (OPS-001).
#
#   git fetch -q origin main
#   GENERATED_PATHS="data/internal/research/injuries/" LOG_PREFIX="nfl-event-window" bash scripts/ci/rebase-onto-main.sh
#
# Exit 0: HEAD now sits on origin/main and may be pushed. Exit 1: it does not — the reason is printed as a
# ::error::, the rebase is aborted (the run's commits stay on HEAD, unmodified), and nothing is forced.
#
# Shared by commit-generated.sh and nfl-event-window's single publish step. The publish step used to run a bare
# `git pull --rebase` under `set -e`: on 2026-10-11 (run 38150059664) a conflict on another sport's regenerated
# injury snapshot killed the step before its retry, and the window's two commits were thrown away with the runner.
#
# Rules (unchanged from commit-generated.sh, P257 / V17 W1–W2 / OPS-001a):
#   · only paths under GENERATED_PATHS may be auto-resolved, to THIS run's copy (the later regeneration);
#   · the protected first-publication-wins files are never auto-resolved, whatever GENERATED_PATHS says;
#   · a rebase that cannot start (e.g. an untracked file in the way) is reported, never retried unchanged.
set -euo pipefail
: "${GENERATED_PATHS:?GENERATED_PATHS required (space-separated path prefixes; may be a single space for none)}"
P="${LOG_PREFIX:-commit-generated}"
# v1.7 shadow-integrity audit: a shadow day file is a FIRST-PUBLICATION-WINS artifact. Two runs that both
# created it would otherwise be resolved to the later copy — the S7 rewrite in a new place — so it is
# refused like the money files, whatever GENERATED_PATHS says (docs/V17_WORKFLOW_AUDIT.md W2).
# Results V2 B-4a: a frozen daily Top-5 board is FIRST-PUBLICATION-WINS for the same reason.
PROTECTED_RE='(^|/)mr-dub/(portfolio|ledger|daily-summary|banked-ladders)\.json$|(^|/)data/internal/products/selector-shadow/|(^|/)public/data/results/top-boards/'

rebasing() { [ -d "$(git rev-parse --git-path rebase-merge)" ] || [ -d "$(git rev-parse --git-path rebase-apply)" ]; }
allowed() { local f="$1"; [[ "$f" =~ $PROTECTED_RE ]] && return 1; for p in $GENERATED_PATHS; do [[ "$f" == "$p"* ]] && return 0; done; return 1; }

# --autostash (docs/V17_WORKFLOW_AUDIT.md W1): a caller may leave stamp-only files MODIFIED but unstaged, and
# `git rebase` refuses a dirty tree. The autostash carries the unstaged edits across the rebase.
if ! rebase_out=$(git rebase -q --autostash origin/main 2>&1); then
  # OPS-001 (ufc-fight-week run 38065746333, 2026-10-10 16:02Z): a rebase can fail WITHOUT starting — e.g.
  # "untracked working tree files would be overwritten". Nothing is unmerged; say what git said and stop.
  if ! rebasing && [ -z "$(git diff --name-only --diff-filter=U)" ]; then
    echo "::error::$P: rebase onto origin/main could not start — not retrying an unchanged commit"
    printf '%s\n' "$rebase_out" | sed 's/^/  git: /'
    exit 1
  fi
  # A content conflict. During a rebase, "theirs" is the commit being replayed — this run's version.
  while true; do
    conflicted=$(git diff --name-only --diff-filter=U)
    [ -z "$conflicted" ] && break
    for f in $conflicted; do
      if allowed "$f"; then
        git checkout --theirs -- "$f" && git add -- "$f"
        echo "$P: $f regenerated by two runs — this run's (later) copy kept"
      else
        echo "::error::$P: conflict on $f, which is not a regenerable path — aborting, nothing forced"
        git rebase --abort; exit 1
      fi
    done
    if ! GIT_EDITOR=true git rebase --continue >/dev/null 2>&1; then
      [ -n "$(git diff --name-only --diff-filter=U)" ] && continue
      git rebase --skip >/dev/null 2>&1 || true   # our commit became empty: the other run already published it
    fi
    rebasing || break
  done
fi
# Only a commit that now sits on the fetched main may be pushed; re-pushing one that did not move can only be
# rejected again.
if ! git merge-base --is-ancestor origin/main HEAD; then
  echo "::error::$P: HEAD is still not on origin/main after the rebase — not retrying an unchanged commit"
  exit 1
fi
