"""
Phase 7C — settle generated leans against actual final stats.

Inputs:
  pipeline/validation/leans_log.jsonl     — append-only log of every lean
                                             ever generated by the pipeline
  pipeline/overrides/results_overrides.json — manual final-stat overrides

Outputs:
  pipeline/validation/settled_leans.jsonl              — append-and-update,
                                                          one row per settled
                                                          (lean, bookmaker)
  pipeline/validation/comparison_report_<date>.json    — aggregated stats

Usage:
  python -m pipeline.settle_results --date 2026-05-05
  python -m pipeline.settle_results --date 2026-05-05 --manual-only
  python -m pipeline.settle_results --date 2026-05-05 --dry-run

Sources (in priority order):
  1. Manual override file (always wins)
  2. nba_api boxscore (auto, when network + matching NBA.com gameId)
  3. ESPN summary boxscore (auto, when gameId is ESPN's 9-digit event id
     — added so playoff games whose boards came from espn_scoreboard
     still settle without a manual override)
  4. (none) → result = "stats_unavailable"

Settlement rules:
  - side=Over, finalStat > line  → win
  - side=Over, finalStat < line  → loss
  - side=Under, finalStat < line → win
  - side=Under, finalStat > line → loss
  - finalStat == line            → push
  - market not in (PTS, REB, AST) → result=invalid
  - line is None / non-numeric    → result=invalid
  - finalStat is None             → result=stats_unavailable
  - side not in (Over, Under)     → row SKIPPED (not a pickable side)

Idempotency:
  Re-running for the same date REWRITES that date's rows in
  settled_leans.jsonl. Other dates are preserved verbatim.

Honest framing:
  No ROI. No profitability claims. Hit rate excludes pushes. The script
  flags any aggregation with fewer than 25 decisive picks as not
  statistically meaningful.
"""
