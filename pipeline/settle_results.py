SUPPORTED_MARKETS = nba_settle.SUPPORTED_MARKETS
PICK_SIDES = ("Over", "Under")
SAMPLE_SIZE_FLOOR = 25  # below this, mark sampleSizeWarning


# ---------------------------------------------------------------------------
# Time helper
# ---------------------------------------------------------------------------
def iso_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# ---------------------------------------------------------------------------
# Read leans log
# ---------------------------------------------------------------------------
def read_leans_for_date(date: str) -> list[dict]:
    """Read every lean from the append-only log for the given date.

    Some early leans were written to the log BEFORE `enrich_board.py`
    populated `lean`/`projection` (their `confidence` was logged as
    "trends_pending"). When that happens, hydrate the row from the
    authoritative public board file so settlement uses the side the
    user actually saw on the live site.

    Pure read; never overwrites a log entry. Returns merged rows for
    consumption by the rest of this module.
    """
    if not LEANS_LOG_PATH.exists():
        return []
    out: list[dict] = []
    board_lookup = _load_board_lean_lookup(date)
    with LEANS_LOG_PATH.open() as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("date") != date:
                continue
            needs_hydrate = (
                not row.get("lean")
                and not row.get("side")
                and board_lookup is not None
            )
            if needs_hydrate:
                key = (row.get("playerId"), row.get("market"))
                board_lean = board_lookup.get(key)
                if board_lean is not None:
                    # Only merge fields that are missing/None on the log row.
                    for field in (
                        "lean",
                        "side",
                        "modelProjection",
                        "projection",
                        "confidence",
                        "edgePct",
                        "riskFlags",
                    ):
                        if row.get(field) in (None, "trends_pending"):
                            val = board_lean.get(field)
                            if val is not None:
                                row[field] = val
            out.append(row)
    return out


def _load_board_lean_lookup(date: str) -> dict | None:
    """Build a {(playerId, market): board_lean_dict} lookup from the
    public board JSON for `date`. Returns None when no board file is
    on disk; the caller falls back to logged values only."""
    path = BOARDS_DIR / f"{date}.json"
    if not path.exists():
        return None
    try:
        board = json.loads(path.read_text())
    except json.JSONDecodeError:
        return None
    lookup: dict[tuple, dict] = {}
    for lean in board.get("leans") or []:
        key = (lean.get("playerId"), lean.get("market"))
        if key[0] is None or key[1] is None:
            continue
        lookup[key] = lean
    return lookup


# ---------------------------------------------------------------------------
# Manual overrides
# ---------------------------------------------------------------------------
def load_overrides(date: str) -> dict[tuple[str, str | None], dict[str, float]]:
    """
    Load manual final-stat overrides for the given date.

    Returns a dict keyed by (normalized_player_name, team_or_None) → {PTS, REB, AST}.
    Both (name, team) and (name, None) are added so settlement can match
    even when team metadata is missing on the lean.
    """
    if not OVERRIDES_PATH.exists():
        return {}

    try:
        data = json.loads(OVERRIDES_PATH.read_text())
    except json.JSONDecodeError as e:
        log.warning(f"results_overrides.json is not valid JSON: {e}")
        return {}

    if not isinstance(data, dict):
        log.warning("results_overrides.json must be a JSON object at top level")
        return {}

    if data.get("date") != date:
        log.info(
            f"override file is for date {data.get('date')!r}; "
            f"requested {date!r} — skipping override"
        )
        return {}

    out: dict[tuple[str, str | None], dict[str, float]] = {}
    games = data.get("games") or []
    if not isinstance(games, list):
        log.warning("override 'games' field must be a list — skipping")
        return {}

    for game in games:
        if not isinstance(game, dict):
            continue
        players = game.get("players") or []
        if not isinstance(players, list):
            continue

        for player in players:
            if not isinstance(player, dict):
                continue
            name = (player.get("playerName") or "").strip().lower()
            if not name:
                continue
            team = player.get("team")

            stats: dict[str, float] = {}
            for k in SUPPORTED_MARKETS:
                v = player.get(k)
                if isinstance(v, (int, float)) and not isinstance(v, bool):
                    stats[k] = float(v)

            if not stats:
                continue

            out[(name, team)] = stats
            # Also key by (name, None) for fallback when lean's team is missing
            if (name, None) not in out:
                out[(name, None)] = stats

    return out


# ---------------------------------------------------------------------------
# Optional nba_api boxscore — auto source, never required
# ---------------------------------------------------------------------------
def fetch_final_stats_via_espn(
    game_id: str,
    *,
    fetch_json: Callable[[str], dict[str, Any] | None] | None = None,
) -> dict[str, dict[str, float]] | None:
    """
    Fetch per-player final stats for an NBA game via ESPN's `summary`
    endpoint. Returns {normalized_player_name: {PTS, REB, AST}} or None
    on any failure.

    Keyed by lowercased player name (not NBA.com playerId) because the
    ESPN payload only carries ESPN athlete ids, not NBA.com ones. The
    settle pipeline keys leans by (playerName, gameId) when this source
    fires — sufficient since each game's box score has unique names.

    Pure-ish: network call only when `fetch_json` is None. Tests inject
    a fake fetcher to stay offline.
    """
    if not game_id:
        return None
    # Only attempt ESPN when the gameId looks like an ESPN event id
    # (9-digit integer string). NBA.com ids are 10-digit zero-padded
    # strings like "0042500207" — those go to the nba_api path.
    if not (game_id.isdigit() and len(game_id) == 9):
        return None
    url = (
        "https://site.api.espn.com/apis/site/v2/sports/basketball/nba/"
        f"summary?event={game_id}"
    )
    if fetch_json is None:
        try:
            import urllib.request

            with urllib.request.urlopen(url, timeout=15) as resp:  # noqa: S310
                payload = json.loads(resp.read().decode("utf-8"))
        except Exception as e:
            log.warning(f"ESPN summary failed for game_id={game_id!r}: {e}")
            return None
    else:
        payload = fetch_json(url)
        if payload is None:
            return None

    try:
        # Refuse to settle a game that ESPN itself does not call FINAL.
        comp = (
            payload.get("header", {})
            .get("competitions", [{}])[0]
        )
        status = comp.get("status", {}).get("type", {})
        if not status.get("completed"):
            log.info(
                f"ESPN game {game_id!r} not final (state={status.get('state')!r}); "
                "skipping ESPN source"
            )
            return None
        out: dict[str, dict[str, float]] = {}
        boxscore = payload.get("boxscore", {})
        for team_data in boxscore.get("players", []) or []:
            for stat_group in team_data.get("statistics", []) or []:
                keys = stat_group.get("keys") or []
                # Column readers for every settleable market, from the one field map in
                # pipeline/nba/settle_results.py. The three-point column is a combined
                # "made-attempted" cell, so it needs a different reader than the scalars — which is
                # exactly the detail a per-call-site index dict got wrong by omitting it.
                readers = nba_settle.espn_stat_readers(keys)
                if not readers:
                    continue
                for athlete in stat_group.get("athletes", []) or []:
                    if athlete.get("didNotPlay"):
                        # DNPs don't get final stats; settlement will mark
                        # these stats_unavailable for the player's markets.
                        continue
                    name = (
                        athlete.get("athlete", {}).get("displayName") or ""
                    ).strip().lower()
                    if not name:
                        continue
                    stats_arr = athlete.get("stats") or []
                    stats = nba_settle.extract_espn_stats(stats_arr, readers)
                    if stats:
                        out[name] = stats
        return out if out else None
    except Exception as e:
        log.warning(f"ESPN summary parse failed for game_id={game_id!r}: {e}")
        return None


def fetch_final_stats_via_nba_api(game_id: str) -> dict[int, dict[str, float]] | None:
    """
    Fetch per-player final stats for an NBA game via nba_api's
    BoxScoreTraditionalV2 endpoint.

    Returns {playerId: {PTS, REB, AST}} or None on any failure
    (network, ImportError, malformed response, non-NBA game_id).

    The pipeline's gameId is sometimes a synthetic "manual-{date}-{home}-{away}"
    string for manual-override schedule days; nba_api will fail for those.
    That's fine — we return None and fall back to the override file.
    """
    try:
        from nba_api.stats.endpoints import boxscoretraditionalv2
    except ImportError:
        log.info("nba_api not installed — skipping auto source")
        return None

    try:
        bx = boxscoretraditionalv2.BoxScoreTraditionalV2(
            game_id=game_id, timeout=15
        )
        frames = bx.get_data_frames()
        if not frames:
            return None
        df = frames[0]
        out: dict[int, dict[str, float]] = {}
        for _, row in df.iterrows():
            try:
                pid = int(row["PLAYER_ID"])
            except (KeyError, ValueError, TypeError):
                continue
            stats = nba_settle.extract_nba_api_stats(row)
            if stats:
                out[pid] = stats
        return out if out else None
    except Exception as e:
        log.warning(f"nba_api boxscore failed for game_id={game_id!r}: {e}")
        return None


def _nba_abbr_match(a: str | None, b: str | None) -> bool:
    """
    Tolerant NBA team-abbreviation comparison.

    Our boards and ESPN disagree on a handful of abbreviations
    (ESPN: "SA"/"GS"/"NO"/"NY"/"UTAH"/"WSH"; boards: "SAS"/"GSW"/"NOP"/
    "NYK"/"UTA"/"WAS"). Rather than maintain an exhaustive alias table,
    two abbreviations are treated as the same franchise when either is a
    prefix of the other (case-insensitive, min length 2). That collapses
    SA/SAS, GS/GSW, NO/NOP, NY/NYK, UTA/UTAH without hard-coding every
    team. False collisions are effectively impossible because both
    abbreviations must also belong to the *same* scoreboard event.
    """
    a = (a or "").strip().upper()
    b = (b or "").strip().upper()
    if len(a) < 2 or len(b) < 2:
        return False
    return a == b or a.startswith(b) or b.startswith(a)


def resolve_espn_event_id_for_teams(
    date: str,
    team: str | None,
    opponent: str | None,
    *,
    fetch_json: Callable[[str], dict[str, Any] | None] | None = None,
) -> str | None:
    """
    Resolve an ESPN NBA event id from a game date + the two team
    abbreviations on our board.

    Why this exists: our NBA boards key games by NBA.com 10-digit game
    ids (e.g. "0042500317"). When nba_api is unavailable — not installed,
    or NBA.com blocks the runner's IP, which is common on CI — settlement
    has no way to fetch the box score, because `fetch_final_stats_via_espn`
    only accepts ESPN's own 9-digit event ids. This bridges the two id
    spaces using only the public ESPN scoreboard (no key, not IP-blocked),
    so a final game still settles from official stats instead of being
    left perpetually `stats_unavailable`.

    Returns the ESPN event id string, or None when no game on that date
    matches both team abbreviations one-to-one.

    Pure-ish: network only when `fetch_json` is None (tests inject a fake
    fetcher to stay offline).
    """
    if not date or not team or not opponent:
        return None
    ymd = date.replace("-", "")
    if not (len(ymd) == 8 and ymd.isdigit()):
        return None
    url = (
        "https://site.api.espn.com/apis/site/v2/sports/basketball/nba/"
        f"scoreboard?dates={ymd}"
    )
    if fetch_json is None:
        try:
            import urllib.request

            with urllib.request.urlopen(url, timeout=15) as resp:  # noqa: S310
                payload = json.loads(resp.read().decode("utf-8"))
        except Exception as e:
            log.warning(f"ESPN scoreboard failed for date={date!r}: {e}")
            return None
    else:
        payload = fetch_json(url)
        if payload is None:
            return None

    try:
        want = [team, opponent]
        for event in payload.get("events", []) or []:
            comps = (event.get("competitions") or [{}])[0].get(
                "competitors", []
            )
            abbrs = [
                (c.get("team", {}) or {}).get("abbreviation") for c in comps
            ]
            if len(abbrs) != 2:
                continue
            # Both board abbreviations must match the two ESPN
            # abbreviations one-to-one (no reusing a side twice).
            used = [False, False]
            matched_all = True
            for w in want:
                hit = False
                for i, eb in enumerate(abbrs):
                    if not used[i] and _nba_abbr_match(w, eb):
                        used[i] = True
                        hit = True
                        break
                if not hit:
                    matched_all = False
                    break
            if matched_all:
                eid = event.get("id")
                return str(eid) if eid is not None else None
        return None
    except Exception as e:
        log.warning(f"ESPN scoreboard parse failed for date={date!r}: {e}")
        return None


# ---------------------------------------------------------------------------
# Resolve final stat for a single lean
# ---------------------------------------------------------------------------
def resolve_final_stat(
    lean: dict,
    overrides: dict[tuple[str, str | None], dict[str, float]],
    auto_stats_by_game: dict[str, dict[int, dict[str, float]]],
    espn_stats_by_game: dict[str, dict[str, dict[str, float]]] | None = None,
) -> tuple[float | None, str]:
    """Returns (final_stat, source) where source is one of:
       'manual_override', 'nba_api', 'espn', 'missing'."""
    name = (lean.get("playerName") or "").strip().lower()
    team = lean.get("team")
    market = lean.get("market")

    if not name or not market:
        return None, "missing"

    # 1. Override (with team match preferred)
    for key in ((name, team), (name, None)):
        if key in overrides and market in overrides[key]:
            return overrides[key][market], "manual_override"

    # 2. nba_api auto (keyed by NBA.com playerId, only when nba_api accepts
    #    the gameId — i.e. NBA.com 10-digit ids)
    pid = lean.get("playerId")
    game_id = lean.get("gameId")
    if pid is not None and game_id and game_id in auto_stats_by_game:
        stats = auto_stats_by_game[game_id].get(int(pid))
        if stats and market in stats:
            return stats[market], "nba_api"

    # 3. ESPN summary auto (keyed by lowercased player name; covers
    #    games whose boards came from espn_scoreboard, e.g. playoff days
    #    when nba_api's playoff stats endpoint is down)
    if espn_stats_by_game and game_id and game_id in espn_stats_by_game:
        stats = espn_stats_by_game[game_id].get(name)
        if stats and market in stats:
            return stats[market], "espn"

    return None, "missing"


# ---------------------------------------------------------------------------
# Settle a single lean — pure function; tested directly
# ---------------------------------------------------------------------------
def settle_lean(
    lean: dict,
    final_stat: float | None,
    settlement_source: str,
    game_status: str | None = None,
) -> dict | None:
    """
    Settle a single lean.

    Returns a settled-row dict, or None if the lean is not settleable
    (e.g. side="No Play"/"Pass" — these are intentionally skipped).

    `game_status`, when the caller knows it, quarantines legs tied to a game the league did not
    play as scheduled. A postponed game has no final box score for THIS instance and never will;
    grading it win/loss would be a result read off a game that did not happen, and leaving it
    pending forever is the silent-omission failure soccer shipped 192 times.
    """
    side = lean.get("lean") or lean.get("side")
    if side not in PICK_SIDES:
        return None  # Not a pickable side; skip

    base = {
        "date": lean.get("date"),
        "gameId": lean.get("gameId"),
        "playerId": lean.get("playerId"),
        "playerName": lean.get("playerName"),
        "team": lean.get("team"),
        "opponent": lean.get("opponent"),
        "market": lean.get("market"),
        "side": side,
        "line": lean.get("line"),
        "bookmaker": lean.get("bookmaker"),
        "oddsOver": lean.get("oddsOver"),
        "oddsUnder": lean.get("oddsUnder"),
        "modelProjection": lean.get("modelProjection") or lean.get("projection"),
        "edgePct": lean.get("edgePct"),
        "confidence": lean.get("confidence"),
        "settlementSource": settlement_source,
        "settledAt": iso_now(),
    }

    market = lean.get("market")
    line = lean.get("line")

    if nba_settle.is_quarantined_status(game_status):
        return nba_settle.quarantine_row(base, game_status)

    # Date-gated whitelist. Historical dates resolve to the legacy three, so re-running settlement
    # over the 2026 corpus reproduces its `invalid` rows byte for byte instead of restamping them.
    if market not in nba_settle.supported_markets_for_date(lean.get("date")):
        return {
            **base,
            "result": "invalid",
            "failureReason": f"unsupported market {market!r}",
        }

    if not isinstance(line, (int, float)) or isinstance(line, bool):
        return {
            **base,
            "result": "invalid",
            "failureReason": "missing or non-numeric line",
        }

    if final_stat is None:
        return {
            **base,
            "result": "stats_unavailable",
            "failureReason": "no final stat available from any source",
        }

    # Determine W/L/P
    if final_stat > line:
        result = "win" if side == "Over" else "loss"
    elif final_stat < line:
        result = "loss" if side == "Over" else "win"
    else:
        result = "push"

    finalized = {**base, "finalStat": float(final_stat), "result": result}

    proj = base["modelProjection"]
    if isinstance(proj, (int, float)) and not isinstance(proj, bool):
        finalized["projectionError"] = round(float(proj) - float(final_stat), 4)
        finalized["absoluteProjectionError"] = round(
            abs(float(proj) - float(final_stat)), 4
        )

    return finalized


# ---------------------------------------------------------------------------
# Idempotent JSONL write
# ---------------------------------------------------------------------------
def write_settled_jsonl(date: str, new_rows: list[dict]) -> None:
    """
    Rewrite settled_leans.jsonl: keep all rows for OTHER dates verbatim,
    replace this date's rows with new_rows. Atomic via temp file.
    """
    SETTLED_PATH.parent.mkdir(parents=True, exist_ok=True)

    preserved: list[dict] = []
    if SETTLED_PATH.exists():
        for line in SETTLED_PATH.read_text().splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("date") != date:
                preserved.append(row)

    tmp = SETTLED_PATH.with_suffix(".jsonl.tmp")
    with tmp.open("w") as f:
        for row in preserved:
            f.write(json.dumps(row, sort_keys=True) + "\n")
        for row in new_rows:
            f.write(json.dumps(row, sort_keys=True) + "\n")
    tmp.replace(SETTLED_PATH)


# ---------------------------------------------------------------------------
# Comparison report aggregation
# ---------------------------------------------------------------------------
def _bucket(rows: list[dict], key_fn: Callable[[dict], Any]) -> dict:
    out: dict[str, dict] = {}
    for r in rows:
        k = str(key_fn(r))
        if k not in out:
            out[k] = {"wins": 0, "losses": 0, "pushes": 0, "total": 0}
        out[k]["total"] += 1
        result = r.get("result")
        if result == "win":
            out[k]["wins"] += 1
        elif result == "loss":
            out[k]["losses"] += 1
        elif result == "push":
            out[k]["pushes"] += 1
    for k, b in out.items():
        decisive = b["wins"] + b["losses"]
        b["decisive"] = decisive
        b["hitRate"] = (b["wins"] / decisive) if decisive > 0 else None
    return out


def build_comparison_report(date: str, all_rows_for_date: list[dict]) -> dict:
    """
    Build the comparison report from all settled rows for one date.
    Includes invalid + stats_unavailable in totals (transparent counts) but
    excludes them from hit-rate aggregations.
    """
    settled = [
        r for r in all_rows_for_date if r.get("result") in ("win", "loss", "push")
    ]
    n_settled = len(settled)
    n_total = len(all_rows_for_date)
    n_unavailable = sum(
        1 for r in all_rows_for_date if r.get("result") == "stats_unavailable"
    )
    n_invalid = sum(
        1 for r in all_rows_for_date if r.get("result") == "invalid"
    )

    wins = sum(1 for r in settled if r["result"] == "win")
    losses = sum(1 for r in settled if r["result"] == "loss")
    pushes = sum(1 for r in settled if r["result"] == "push")
    decisive = wins + losses
    hit_rate = (wins / decisive) if decisive > 0 else None

    proj_errors = [
        r["projectionError"] for r in settled if "projectionError" in r
    ]
    abs_proj_errors = [
        r["absoluteProjectionError"]
        for r in settled
        if "absoluteProjectionError" in r
    ]
    avg_proj_error = (
        round(sum(proj_errors) / len(proj_errors), 4) if proj_errors else None
    )
    avg_abs_proj_error = (
        round(sum(abs_proj_errors) / len(abs_proj_errors), 4)
        if abs_proj_errors
        else None
    )

    by_market = _bucket(settled, lambda r: r.get("market", "?"))
    by_confidence = _bucket(settled, lambda r: r.get("confidence", "?"))
    by_game = _bucket(settled, lambda r: r.get("gameId", "?"))
    by_book = _bucket(settled, lambda r: r.get("bookmaker", "?"))

    largest_misses = sorted(
        (r for r in settled if "absoluteProjectionError" in r),
        key=lambda r: -r["absoluteProjectionError"],
    )[:5]
    largest_misses_summary = [
        {
            "playerName": r.get("playerName"),
            "market": r.get("market"),
            "side": r.get("side"),
            "line": r.get("line"),
            "modelProjection": r.get("modelProjection"),
            "finalStat": r.get("finalStat"),
            "absoluteProjectionError": r.get("absoluteProjectionError"),
            "result": r.get("result"),
        }
        for r in largest_misses
    ]

    wins_with_edge = [
        r
        for r in settled
        if r["result"] == "win"
        and isinstance(r.get("edgePct"), (int, float))
    ]
    best_calls = sorted(
        wins_with_edge, key=lambda r: -abs(r["edgePct"])
    )[:5]
    best_calls_summary = [
        {
            "playerName": r.get("playerName"),
            "market": r.get("market"),
            "side": r.get("side"),
            "line": r.get("line"),
            "finalStat": r.get("finalStat"),
            "edgePct": r.get("edgePct"),
            "result": r.get("result"),
        }
        for r in best_calls
    ]

    sample_size_warning = None
    if 0 < decisive < SAMPLE_SIZE_FLOOR:
        sample_size_warning = (
            f"Only {decisive} decisive settlements. Hit rates are not "
            f"statistically meaningful below ~{SAMPLE_SIZE_FLOOR} picks; "
            "treat as descriptive only."
        )

    return {
        "date": date,
        "generatedAt": iso_now(),
        "totalRows": n_total,
        "totalSettled": n_settled,
        "decisive": decisive,
        "wins": wins,
        "losses": losses,
        "pushes": pushes,
        "statsUnavailable": n_unavailable,
        "invalid": n_invalid,
        "hitRate": hit_rate,
        "averageProjectionError": avg_proj_error,
        "averageAbsoluteProjectionError": avg_abs_proj_error,
        "byMarket": by_market,
        "byConfidence": by_confidence,
        "byGame": by_game,
        "byBookmaker": by_book,
        "largestMisses": largest_misses_summary,
        "bestCalls": best_calls_summary,
        "sampleSizeWarning": sample_size_warning,
        "_disclaimer": (
            "Hit rate excludes pushes from the denominator. No ROI shown. "
            "Educational use only — not betting advice."
        ),
    }


