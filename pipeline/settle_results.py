"""
Phase 7C — settle generated leans against actual final stats.

Inputs:
  pipeline/validation/leans_log.jsonl     — append-only log of every lean
                                             ever generated by the pipeline
  pipeline/overrides/results_overrides.json — manual final-stat overrides

Outputs:
  pipeline/validation/settled_leans.jsonl              — append-and-update,
                                                          one row per settled
                                                          (lean, bookmaker)
  pipeline/validation/comparison_report_<date>.json    — aggregated stats

Usage:
  python -m pipeline.settle_results --date 2026-05-05
  python -m pipeline.settle_results --date 2026-05-05 --manual-only
  python -m pipeline.settle_results --date 2026-05-05 --dry-run

Sources (in priority order):
  1. Manual override file (always wins)
  2. nba_api boxscore (auto, when network + matching gameId)
  3. (none) → result = "stats_unavailable"

Settlement rules:
  - side=Over, finalStat > line  → win
  - side=Over, finalStat < line  → loss
  - side=Under, finalStat < line → win
  - side=Under, finalStat > line → loss
  - finalStat == line            → push
  - market not in (PTS, REB, AST) → result=invalid
  - line is None / non-numeric    → result=invalid
  - finalStat is None             → result=stats_unavailable
  - side not in (Over, Under)     → row SKIPPED (not a pickable side)

Idempotency:
  Re-running for the same date REWRITES that date's rows in
  settled_leans.jsonl. Other dates are preserved verbatim.

Honest framing:
  No ROI. No profitability claims. Hit rate excludes pushes. The script
  flags any aggregation with fewer than 25 decisive picks as not
  statistically meaningful.
"""
from __future__ import annotations

import argparse
import json
import logging
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Iterable


log = logging.getLogger("gtp.settle")
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(name)s %(levelname)s %(message)s",
)


# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
PIPELINE_DIR = Path(__file__).resolve().parent
LEANS_LOG_PATH = PIPELINE_DIR / "validation" / "leans_log.jsonl"
SETTLED_PATH = PIPELINE_DIR / "validation" / "settled_leans.jsonl"
OVERRIDES_PATH = PIPELINE_DIR / "overrides" / "results_overrides.json"
REPORT_DIR = PIPELINE_DIR / "validation"

SUPPORTED_MARKETS = ("PTS", "REB", "AST")
PICK_SIDES = ("Over", "Under")
SAMPLE_SIZE_FLOOR = 25  # below this, mark sampleSizeWarning


# ---------------------------------------------------------------------------
# Time helper
# ---------------------------------------------------------------------------
def iso_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# ---------------------------------------------------------------------------
# Read leans log
# ---------------------------------------------------------------------------
def read_leans_for_date(date: str) -> list[dict]:
    """Read every lean from the append-only log for the given date."""
    if not LEANS_LOG_PATH.exists():
        return []
    out = []
    with LEANS_LOG_PATH.open() as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("date") == date:
                out.append(row)
    return out


# ---------------------------------------------------------------------------
# Manual overrides
# ---------------------------------------------------------------------------
def load_overrides(date: str) -> dict[tuple[str, str | None], dict[str, float]]:
    """
    Load manual final-stat overrides for the given date.

    Returns a dict keyed by (normalized_player_name, team_or_None) → {PTS, REB, AST}.
    Both (name, team) and (name, None) are added so settlement can match
    even when team metadata is missing on the lean.
    """
    if not OVERRIDES_PATH.exists():
        return {}

    try:
        data = json.loads(OVERRIDES_PATH.read_text())
    except json.JSONDecodeError as e:
        log.warning(f"results_overrides.json is not valid JSON: {e}")
        return {}

    if not isinstance(data, dict):
        log.warning("results_overrides.json must be a JSON object at top level")
        return {}

    if data.get("date") != date:
        log.info(
            f"override file is for date {data.get('date')!r}; "
            f"requested {date!r} — skipping override"
        )
        return {}

    out: dict[tuple[str, str | None], dict[str, float]] = {}
    games = data.get("games") or []
    if not isinstance(games, list):
        log.warning("override 'games' field must be a list — skipping")
        return {}

    for game in games:
        if not isinstance(game, dict):
            continue
        players = game.get("players") or []
        if not isinstance(players, list):
            continue

        for player in players:
            if not isinstance(player, dict):
                continue
            name = (player.get("playerName") or "").strip().lower()
            if not name:
                continue
            team = player.get("team")

            stats: dict[str, float] = {}
            for k in SUPPORTED_MARKETS:
                v = player.get(k)
                if isinstance(v, (int, float)) and not isinstance(v, bool):
                    stats[k] = float(v)

            if not stats:
                continue

            out[(name, team)] = stats
            # Also key by (name, None) for fallback when lean's team is missing
            if (name, None) not in out:
                out[(name, None)] = stats

    return out


# ---------------------------------------------------------------------------
# Optional nba_api boxscore — auto source, never required
# ---------------------------------------------------------------------------
def fetch_final_stats_via_nba_api(game_id: str) -> dict[int, dict[str, float]] | None:
    """
    Fetch per-player final stats for an NBA game via nba_api's
    BoxScoreTraditionalV2 endpoint.

    Returns {playerId: {PTS, REB, AST}} or None on any failure
    (network, ImportError, malformed response, non-NBA game_id).

    The pipeline's gameId is sometimes a synthetic "manual-{date}-{home}-{away}"
    string for manual-override schedule days; nba_api will fail for those.
    That's fine — we return None and fall back to the override file.
    """
    try:
        from nba_api.stats.endpoints import boxscoretraditionalv2
    except ImportError:
        log.info("nba_api not installed — skipping auto source")
        return None

    try:
        bx = boxscoretraditionalv2.BoxScoreTraditionalV2(
            game_id=game_id, timeout=15
        )
        frames = bx.get_data_frames()
        if not frames:
            return None
        df = frames[0]
        out: dict[int, dict[str, float]] = {}
        for _, row in df.iterrows():
            try:
                pid = int(row["PLAYER_ID"])
            except (KeyError, ValueError, TypeError):
                continue
            stats: dict[str, float] = {}
            for col, key in [("PTS", "PTS"), ("REB", "REB"), ("AST", "AST")]:
                v = row.get(col)
                if v is not None and not (
                    isinstance(v, float) and v != v  # NaN check
                ):
                    try:
                        stats[key] = float(v)
                    except (TypeError, ValueError):
                        pass
            if stats:
                out[pid] = stats
        return out if out else None
    except Exception as e:
        log.warning(f"nba_api boxscore failed for game_id={game_id!r}: {e}")
        return None


# ---------------------------------------------------------------------------
# Resolve final stat for a single lean
# ---------------------------------------------------------------------------
def resolve_final_stat(
    lean: dict,
    overrides: dict[tuple[str, str | None], dict[str, float]],
    auto_stats_by_game: dict[str, dict[int, dict[str, float]]],
) -> tuple[float | None, str]:
    """Returns (final_stat, source) where source is one of:
       'manual_override', 'nba_api', 'missing'."""
    name = (lean.get("playerName") or "").strip().lower()
    team = lean.get("team")
    market = lean.get("market")

    if not name or not market:
        return None, "missing"

    # 1. Override (with team match preferred)
    for key in ((name, team), (name, None)):
        if key in overrides and market in overrides[key]:
            return overrides[key][market], "manual_override"

    # 2. nba_api auto
    pid = lean.get("playerId")
    game_id = lean.get("gameId")
    if pid is not None and game_id and game_id in auto_stats_by_game:
        stats = auto_stats_by_game[game_id].get(int(pid))
        if stats and market in stats:
            return stats[market], "nba_api"

    return None, "missing"


# ---------------------------------------------------------------------------
# Settle a single lean — pure function; tested directly
# ---------------------------------------------------------------------------
def settle_lean(
    lean: dict,
    final_stat: float | None,
    settlement_source: str,
) -> dict | None:
    """
    Settle a single lean.

    Returns a settled-row dict, or None if the lean is not settleable
    (e.g. side="No Play"/"Pass" — these are intentionally skipped).
    """
    side = lean.get("lean") or lean.get("side")
    if side not in PICK_SIDES:
        return None  # Not a pickable side; skip

    base = {
        "date": lean.get("date"),
        "gameId": lean.get("gameId"),
        "playerId": lean.get("playerId"),
        "playerName": lean.get("playerName"),
        "team": lean.get("team"),
        "opponent": lean.get("opponent"),
        "market": lean.get("market"),
        "side": side,
        "line": lean.get("line"),
        "bookmaker": lean.get("bookmaker"),
        "oddsOver": lean.get("oddsOver"),
        "oddsUnder": lean.get("oddsUnder"),
        "modelProjection": lean.get("modelProjection") or lean.get("projection"),
        "edgePct": lean.get("edgePct"),
        "confidence": lean.get("confidence"),
        "settlementSource": settlement_source,
        "settledAt": iso_now(),
    }

    market = lean.get("market")
    line = lean.get("line")

    if market not in SUPPORTED_MARKETS:
        return {
            **base,
            "result": "invalid",
            "failureReason": f"unsupported market {market!r}",
        }

    if not isinstance(line, (int, float)) or isinstance(line, bool):
        return {
            **base,
            "result": "invalid",
            "failureReason": "missing or non-numeric line",
        }

    if final_stat is None:
        return {
            **base,
            "result": "stats_unavailable",
            "failureReason": "no final stat available from any source",
        }

    # Determine W/L/P
    if final_stat > line:
        result = "win" if side == "Over" else "loss"
    elif final_stat < line:
        result = "loss" if side == "Over" else "win"
    else:
        result = "push"

    finalized = {**base, "finalStat": float(final_stat), "result": result}

    proj = base["modelProjection"]
    if isinstance(proj, (int, float)) and not isinstance(proj, bool):
        finalized["projectionError"] = round(float(proj) - float(final_stat), 4)
        finalized["absoluteProjectionError"] = round(
            abs(float(proj) - float(final_stat)), 4
        )

    return finalized


# ---------------------------------------------------------------------------
# Idempotent JSONL write
# ---------------------------------------------------------------------------
def write_settled_jsonl(date: str, new_rows: list[dict]) -> None:
    """
    Rewrite settled_leans.jsonl: keep all rows for OTHER dates verbatim,
    replace this date's rows with new_rows. Atomic via temp file.
    """
    SETTLED_PATH.parent.mkdir(parents=True, exist_ok=True)

    preserved: list[dict] = []
    if SETTLED_PATH.exists():
        for line in SETTLED_PATH.read_text().splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("date") != date:
                preserved.append(row)

    tmp = SETTLED_PATH.with_suffix(".jsonl.tmp")
    with tmp.open("w") as f:
        for row in preserved:
            f.write(json.dumps(row, sort_keys=True) + "\n")
        for row in new_rows:
            f.write(json.dumps(row, sort_keys=True) + "\n")
    tmp.replace(SETTLED_PATH)


# ---------------------------------------------------------------------------
# Comparison report aggregation
# ---------------------------------------------------------------------------
def _bucket(rows: list[dict], key_fn: Callable[[dict], Any]) -> dict:
    out: dict[str, dict] = {}
    for r in rows:
        k = str(key_fn(r))
        if k not in out:
            out[k] = {"wins": 0, "losses": 0, "pushes": 0, "total": 0}
        out[k]["total"] += 1
        result = r.get("result")
        if result == "win":
            out[k]["wins"] += 1
        elif result == "loss":
            out[k]["losses"] += 1
        elif result == "push":
            out[k]["pushes"] += 1
    for k, b in out.items():
        decisive = b["wins"] + b["losses"]
        b["decisive"] = decisive
        b["hitRate"] = (b["wins"] / decisive) if decisive > 0 else None
    return out


def build_comparison_report(date: str, all_rows_for_date: list[dict]) -> dict:
    """
    Build the comparison report from all settled rows for one date.
    Includes invalid + stats_unavailable in totals (transparent counts) but
    excludes them from hit-rate aggregations.
    """
    settled = [
        r for r in all_rows_for_date if r.get("result") in ("win", "loss", "push")
    ]
    n_settled = len(settled)
    n_total = len(all_rows_for_date)
    n_unavailable = sum(
        1 for r in all_rows_for_date if r.get("result") == "stats_unavailable"
    )
    n_invalid = sum(
        1 for r in all_rows_for_date if r.get("result") == "invalid"
    )

    wins = sum(1 for r in settled if r["result"] == "win")
    losses = sum(1 for r in settled if r["result"] == "loss")
    pushes = sum(1 for r in settled if r["result"] == "push")
    decisive = wins + losses
    hit_rate = (wins / decisive) if decisive > 0 else None

    proj_errors = [
        r["projectionError"] for r in settled if "projectionError" in r
    ]
    abs_proj_errors = [
        r["absoluteProjectionError"]
        for r in settled
        if "absoluteProjectionError" in r
    ]
    avg_proj_error = (
        round(sum(proj_errors) / len(proj_errors), 4) if proj_errors else None
    )
    avg_abs_proj_error = (
        round(sum(abs_proj_errors) / len(abs_proj_errors), 4)
        if abs_proj_errors
        else None
    )

    by_market = _bucket(settled, lambda r: r.get("market", "?"))
    by_confidence = _bucket(settled, lambda r: r.get("confidence", "?"))
    by_game = _bucket(settled, lambda r: r.get("gameId", "?"))
    by_book = _bucket(settled, lambda r: r.get("bookmaker", "?"))

    largest_misses = sorted(
        (r for r in settled if "absoluteProjectionError" in r),
        key=lambda r: -r["absoluteProjectionError"],
    )[:5]
    largest_misses_summary = [
        {
            "playerName": r.get("playerName"),
            "market": r.get("market"),
            "side": r.get("side"),
            "line": r.get("line"),
            "modelProjection": r.get("modelProjection"),
            "finalStat": r.get("finalStat"),
            "absoluteProjectionError": r.get("absoluteProjectionError"),
            "result": r.get("result"),
        }
        for r in largest_misses
    ]

    wins_with_edge = [
        r
        for r in settled
        if r["result"] == "win"
        and isinstance(r.get("edgePct"), (int, float))
    ]
    best_calls = sorted(
        wins_with_edge, key=lambda r: -abs(r["edgePct"])
    )[:5]
    best_calls_summary = [
        {
            "playerName": r.get("playerName"),
            "market": r.get("market"),
            "side": r.get("side"),
            "line": r.get("line"),
            "finalStat": r.get("finalStat"),
            "edgePct": r.get("edgePct"),
            "result": r.get("result"),
        }
        for r in best_calls
    ]

    sample_size_warning = None
    if 0 < decisive < SAMPLE_SIZE_FLOOR:
        sample_size_warning = (
            f"Only {decisive} decisive settlements. Hit rates are not "
            f"statistically meaningful below ~{SAMPLE_SIZE_FLOOR} picks; "
            "treat as descriptive only."
        )

    return {
        "date": date,
        "generatedAt": iso_now(),
        "totalRows": n_total,
        "totalSettled": n_settled,
        "decisive": decisive,
        "wins": wins,
        "losses": losses,
        "pushes": pushes,
        "statsUnavailable": n_unavailable,
        "invalid": n_invalid,
        "hitRate": hit_rate,
        "averageProjectionError": avg_proj_error,
        "averageAbsoluteProjectionError": avg_abs_proj_error,
        "byMarket": by_market,
        "byConfidence": by_confidence,
        "byGame": by_game,
        "byBookmaker": by_book,
        "largestMisses": largest_misses_summary,
        "bestCalls": best_calls_summary,
        "sampleSizeWarning": sample_size_warning,
        "_disclaimer": (
            "Hit rate excludes pushes from the denominator. No ROI shown. "
            "Educational use only — not betting advice."
        ),
    }


# ---------------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------------
def settle_for_date(
    date: str,
    leans: list[dict],
    *,
    use_auto: bool = True,
) -> tuple[list[dict], dict]:
    """
    Returns (new_settled_rows, summary_dict).

    Pure-ish: file I/O for overrides + (optionally) nba_api network only.
    No file writes here — caller decides where to write.
    """
    overrides = load_overrides(date)

    auto_stats_by_game: dict[str, dict[int, dict[str, float]]] = {}
    if use_auto:
        unique_game_ids = {
            l.get("gameId") for l in leans if l.get("gameId")
        }
        for gid in unique_game_ids:
            stats = fetch_final_stats_via_nba_api(gid)
            if stats:
                auto_stats_by_game[gid] = stats

    settled_rows: list[dict] = []
    skipped_no_pick = 0

    for lean in leans:
        final_stat, source = resolve_final_stat(
            lean, overrides, auto_stats_by_game
        )
        row = settle_lean(lean, final_stat, source)
        if row is None:
            skipped_no_pick += 1
            continue
        settled_rows.append(row)

    decisive_results = {"win", "loss", "push"}
    summary = {
        "date": date,
        "leansRead": len(leans),
        "skippedNoPick": skipped_no_pick,
        "settled": sum(
            1 for r in settled_rows if r.get("result") in decisive_results
        ),
        "wins": sum(1 for r in settled_rows if r.get("result") == "win"),
        "losses": sum(1 for r in settled_rows if r.get("result") == "loss"),
        "pushes": sum(1 for r in settled_rows if r.get("result") == "push"),
        "statsUnavailable": sum(
            1 for r in settled_rows if r.get("result") == "stats_unavailable"
        ),
        "invalid": sum(
            1 for r in settled_rows if r.get("result") == "invalid"
        ),
        "overridesLoaded": len(overrides),
        "autoSourceGames": len(auto_stats_by_game),
    }
    return settled_rows, summary


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------
def _print_summary(date: str, summary: dict, settled_rows: list[dict]) -> None:
    print()
    print(f"  Settlement summary — {date}")
    print(f"  ─────────────────────────────────")
    print(f"  Leans read (excl. No-Play):  {summary['leansRead'] - summary['skippedNoPick']}")
    print(f"  Skipped (No Play / Pass):    {summary['skippedNoPick']}")
    print(f"  Decisive (W/L):              {summary['wins'] + summary['losses']}")
    print(f"    Wins:                      {summary['wins']}")
    print(f"    Losses:                    {summary['losses']}")
    print(f"  Pushes:                      {summary['pushes']}")
    print(f"  Stats unavailable:           {summary['statsUnavailable']}")
    print(f"  Invalid:                     {summary['invalid']}")
    print(f"  Overrides loaded (players):  {summary['overridesLoaded']}")
    print(f"  Auto-source games (nba_api): {summary['autoSourceGames']}")

    decisive = summary["wins"] + summary["losses"]
    if decisive > 0:
        print(f"  Hit rate (excl. pushes):     {summary['wins'] / decisive:.1%}")

    proj_errors = [
        r["absoluteProjectionError"]
        for r in settled_rows
        if "absoluteProjectionError" in r
    ]
    if proj_errors:
        proj_errors_sorted = sorted(proj_errors, reverse=True)
        print(f"  Avg |projection error|:      {sum(proj_errors)/len(proj_errors):.2f}")
        print(f"  Largest |proj. error|:       {proj_errors_sorted[0]:.2f}")
    print()


def main() -> int:
    parser = argparse.ArgumentParser(description="Settle generated leans against final stats.")
    parser.add_argument("--date", required=True, help="YYYY-MM-DD")
    parser.add_argument(
        "--manual-only",
        action="store_true",
        help="Skip the nba_api auto source; settle only with manual overrides",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Don't write any files; just print summary",
    )
    args = parser.parse_args()

    date = args.date
    leans = read_leans_for_date(date)
    if not leans:
        print(f"  No leans logged for {date} in {LEANS_LOG_PATH}.")
        return 1

    new_rows, summary = settle_for_date(
        date, leans, use_auto=not args.manual_only
    )

    if args.dry_run:
        print(f"\n  [dry-run] would write {len(new_rows)} settled rows for {date}")
        _print_summary(date, summary, new_rows)
        return 0

    write_settled_jsonl(date, new_rows)

    # Build comparison report from ALL rows for this date in the file
    all_rows = []
    if SETTLED_PATH.exists():
        for line in SETTLED_PATH.read_text().splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("date") == date:
                all_rows.append(row)

    report = build_comparison_report(date, all_rows)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    report_path = REPORT_DIR / f"comparison_report_{date}.json"
    report_path.write_text(json.dumps(report, indent=2, sort_keys=True))

    _print_summary(date, summary, new_rows)
    print(f"  Settled rows  → {SETTLED_PATH}")
    print(f"  Report        → {report_path}")
    print()

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
