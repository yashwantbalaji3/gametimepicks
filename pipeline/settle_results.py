def settle_for_date(
    date: str,
    leans: list[dict],
    *,
    use_auto: bool = True,
) -> tuple[list[dict], dict]:
    """
    Returns (new_settled_rows, summary_dict).

    Pure-ish: file I/O for overrides + (optionally) nba_api network only.
    No file writes here — caller decides where to write.
    """
    overrides = load_overrides(date)

    auto_stats_by_game: dict[str, dict[int, dict[str, float]]] = {}
    espn_stats_by_game: dict[str, dict[str, dict[str, float]]] = {}
    if use_auto:
        # Map each gameId to a representative (date, team, opponent) from
        # its leans so we can bridge NBA.com ids → ESPN event ids by
        # date+teams when the direct id paths fail. Insertion order is
        # deterministic, which keeps re-runs reproducible.
        gid_meta: dict[str, tuple[str | None, str | None, str | None]] = {}
        for l in leans:
            gid = l.get("gameId")
            if gid and gid not in gid_meta:
                gid_meta[gid] = (
                    l.get("date") or date,
                    l.get("team"),
                    l.get("opponent"),
                )
        # Cache scoreboard lookups by date so a multi-game NBA slate only
        # hits the ESPN scoreboard once per date.
        espn_eid_cache: dict[tuple[str | None, str | None, str | None], str | None] = {}
        for gid in gid_meta:
            # Try nba_api first for NBA.com-format ids; if that fails (or
            # the id is ESPN-format), fall through to ESPN summary.
            stats = fetch_final_stats_via_nba_api(str(gid))
            if stats:
                auto_stats_by_game[gid] = stats
                continue
            espn_stats = fetch_final_stats_via_espn(str(gid))
            if espn_stats:
                espn_stats_by_game[gid] = espn_stats
                continue
            # Last resort: the gameId is an NBA.com id (not an ESPN event
            # id) and nba_api was unavailable. Bridge to ESPN via the
            # public scoreboard (date + team abbreviations), then fetch
            # the ESPN box score. Keeps final games settling from official
            # stats when nba_api is blocked (e.g. on CI runners).
            d, tm, opp = gid_meta[gid]
            meta_key = (d, tm, opp)
            if meta_key not in espn_eid_cache:
                espn_eid_cache[meta_key] = resolve_espn_event_id_for_teams(
                    d, tm, opp
                )
            espn_eid = espn_eid_cache[meta_key]
            if espn_eid:
                bridged = fetch_final_stats_via_espn(str(espn_eid))
                if bridged:
                    espn_stats_by_game[gid] = bridged

    settled_rows: list[dict] = []
    skipped_no_pick = 0

    for lean in leans:
        final_stat, source = resolve_final_stat(
            lean, overrides, auto_stats_by_game, espn_stats_by_game
        )
        row = settle_lean(lean, final_stat, source, lean.get("gameStatus"))
        if row is None:
            skipped_no_pick += 1
            continue
        settled_rows.append(row)

    # Fail closed BEFORE anything reaches the ledger, on the validator MLB settlement already runs
    # (Sprint 045; it refused 641 rows on a real collision in Sprint 049). NBA settlement has never
    # run through a lineage gate — a dry run over the 2026 corpus refuses it on two shapes, which is
    # recorded in pipeline/nba/settle_results_test.py rather than repaired by restamping.
    nba_settle.assert_nba_settlement_lineage(settled_rows, date=date)

    decisive_results = {"win", "loss", "push"}
    summary = {
        "date": date,
        "leansRead": len(leans),
        "skippedNoPick": skipped_no_pick,
        "settled": sum(
            1 for r in settled_rows if r.get("result") in decisive_results
        ),
        "wins": sum(1 for r in settled_rows if r.get("result") == "win"),
        "losses": sum(1 for r in settled_rows if r.get("result") == "loss"),
        "pushes": sum(1 for r in settled_rows if r.get("result") == "push"),
        "statsUnavailable": sum(
            1 for r in settled_rows if r.get("result") == "stats_unavailable"
        ),
        "invalid": sum(
            1 for r in settled_rows if r.get("result") == "invalid"
        ),
        "overridesLoaded": len(overrides),
        "autoSourceGames": len(auto_stats_by_game),
        "espnSourceGames": len(espn_stats_by_game),
    }
    return settled_rows, summary


