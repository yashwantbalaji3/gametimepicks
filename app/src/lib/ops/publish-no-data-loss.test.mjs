/**
 * OPS-001 (2026-10-13) · A RUN'S COMMITS ARE NEVER SILENTLY LOST AT PUBLISH.
 *
 * nfl-event-window run 38150059664 (2026-10-11 15:13Z) made two commits (the window and its settlement receipts),
 * then its single publish step ran `git pull --rebase` under `set -e`. Another writer outside the concurrency group
 * (nba-forecast-window) had just committed data/internal/research/injuries/nba/latest.json, which the window had also
 * regenerated and staged; the rebase conflicted, the step died before its retry, and both commits went away with the
 * runner. Real git below: a bare origin, the run's clone, and the other writer racing it.
 */
import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync, spawnSync } from "node:child_process";

const REPO = path.resolve(process.cwd(), "..");
const HELPER = path.join(REPO, "scripts/ci/rebase-onto-main.sh");
const ENV = { ...process.env, GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" };
const git = (cwd, ...a) => execFileSync("git", a, { cwd, encoding: "utf8", env: ENV });
const put = (dir, rel, body) => { fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true }); fs.writeFileSync(path.join(dir, rel), body); };

/** The run makes its two commits from an older checkout; the other writer lands `otherFile` first. */
function incident({ otherFile, runAlsoWrites = otherFile }) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "pub-"));
  const origin = path.join(root, "origin.git");
  git(root, "init", "-q", "--bare", "-b", "main", origin);
  const run = path.join(root, "run"), other = path.join(root, "other");
  git(root, "clone", "-q", origin, run);
  put(run, "data/internal/research/injuries/nba/latest.json", '{"v":0}\n');
  put(run, "app/public/data/nfl/weekly-boards/latest.json", '{"v":0}\n');
  git(run, "add", "."); git(run, "commit", "-q", "-m", "seed"); git(run, "push", "-q", "origin", "HEAD:main");
  git(root, "clone", "-q", origin, other);
  // the run: window commit (boards + the shared file) and settlement commit (a write-once receipt)
  put(run, "app/public/data/nfl/weekly-boards/latest.json", '{"v":"run"}\n');
  put(run, runAlsoWrites, '{"v":"run"}\n');
  git(run, "add", "."); git(run, "commit", "-q", "-m", "auto: nfl event window [skip ci]");
  put(run, "data/internal/nfl/settlement/receipt-1.json", '{"write":"once"}\n');
  git(run, "add", "."); git(run, "commit", "-q", "-m", "auto: nfl settlement receipts [skip ci]");
  // the other writer lands first
  put(other, otherFile, '{"v":"other"}\n'); git(other, "add", "."); git(other, "commit", "-q", "-m", "other"); git(other, "push", "-q", "origin", "HEAD:main");
  // the publish step, as written in nfl-event-window.yml
  git(run, "fetch", "-q", "origin", "main");
  const r = spawnSync("bash", [HELPER], { cwd: run, encoding: "utf8", env: { ...ENV, GENERATED_PATHS: "data/internal/research/injuries/", LOG_PREFIX: "nfl-event-window publish" } });
  return { r, run, root, origin };
}

test("🔴 the 2026-10-11 incident: a conflict on a regenerated injury snapshot no longer loses the run — both commits land", () => {
  const { r, run } = incident({ otherFile: "data/internal/research/injuries/nba/latest.json" });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.match(r.stdout, /injuries\/nba\/latest\.json regenerated by two runs — this run's \(later\) copy kept/);
  git(run, "push", "-q", "origin", "HEAD:main");
  const log = git(run, "log", "--format=%s", "origin/main");
  assert.match(log, /auto: nfl event window/);
  assert.match(log, /auto: nfl settlement receipts/);
  assert.equal(fs.readFileSync(path.join(run, "data/internal/nfl/settlement/receipt-1.json"), "utf8"), '{"write":"once"}\n');
});

test("🔴 a conflict on anything else fails LOUD, forces nothing, and leaves both commits on HEAD to be bundled", () => {
  const { r, run } = incident({ otherFile: "app/public/data/nfl/weekly-boards/latest.json" });
  assert.equal(r.status, 1);
  assert.match(r.stdout + r.stderr, /::error::nfl-event-window publish: conflict on app\/public\/data\/nfl\/weekly-boards\/latest\.json, which is not a regenerable path/);
  // not mid-rebase, nothing rewritten: the run's two commits are exactly where they were
  assert.ok(!fs.existsSync(path.join(run, ".git", "rebase-merge")) && !fs.existsSync(path.join(run, ".git", "rebase-apply")));
  const ahead = git(run, "log", "--format=%s", "origin/main..HEAD").trim().split("\n");
  assert.deepEqual(ahead, ["auto: nfl settlement receipts [skip ci]", "auto: nfl event window [skip ci]"]);
  // the recovery step's bundle carries them
  git(run, "bundle", "create", "unpublished-commits.bundle", "origin/main..HEAD");
  const head = git(run, "rev-parse", "HEAD").trim();
  assert.match(git(run, "bundle", "verify", "unpublished-commits.bundle"), new RegExp(`${head} HEAD`), "the bundle carries the run's HEAD");
});

test("a protected first-publication-wins file is never auto-resolved, even under a generated prefix", () => {
  const { r } = incident({ otherFile: "app/public/data/results/top-boards/2026-10-11.json" });
  assert.equal(r.status, 1);
  assert.match(r.stdout + r.stderr, /not a regenerable path/);
});

// ── the workflow wiring ──────────────────────────────────────────────────────────────────────────────────────────
const wf = fs.readFileSync(path.join(REPO, ".github/workflows/nfl-event-window.yml"), "utf8");
const step = (name) => { const at = wf.indexOf(`- name: ${name}`); assert.ok(at > 0, `step "${name}" exists`); const next = wf.indexOf("\n      - name:", at + 1); return wf.slice(at, next < 0 ? undefined : next); };

test("🔴 the publish step rebases through the guarded helper — no bare `git pull --rebase` that set -e can kill", () => {
  const s = step("Publish this run's commits (one push, one deployment)");
  assert.match(s, /id: publish/);
  assert.match(s, /GENERATED_PATHS="data\/internal\/research\/injuries\/"[^\n]*bash scripts\/ci\/rebase-onto-main\.sh/);
  assert.doesNotMatch(s.replace(/^\s*#.*$/gm, ""), /git pull --rebase/);
});

test("🔴 a failed publish keeps the run's commits as an artifact instead of losing them", () => {
  const keep = step("Keep unpublished commits recoverable");
  assert.match(keep, /if: \$\{\{ always\(\) && steps\.publish\.outcome == 'failure' \}\}/);
  assert.match(keep, /git bundle create unpublished-commits\.bundle origin\/main\.\.HEAD/);
  const up = step("Upload unpublished commits");
  assert.match(up, /if: \$\{\{ always\(\) && steps\.publish\.outcome == 'failure' \}\}/);
  assert.match(up, /uses: actions\/upload-artifact@v4/);
  assert.match(up, /unpublished-commits\.bundle/);
});

test("🔴 the window stages only NFL's injury snapshot — NBA's is nba-forecast-window's to commit", () => {
  const adds = wf.replace(/^\s*#.*$/gm, "").match(/git add [^\n]*/g) ?? [];
  const staging = adds.filter((l) => l.includes("injuries"));
  assert.ok(staging.length >= 1, "the injury capture is still committed (P256)");
  for (const l of staging) {
    assert.match(l, /data\/internal\/research\/injuries\/nfl\//);
    assert.doesNotMatch(l, /data\/internal\/research\/injuries\/(\s|$)/, "the whole injuries tree would stage NBA's file too");
  }
});
