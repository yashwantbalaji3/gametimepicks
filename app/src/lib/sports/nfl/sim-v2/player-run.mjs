/**
 * NFL SIM V2 · RE-DERIVING PLAYER LINES FOR A RECEIPT'S STORED RUNS — SCRIPTS AND TESTS ONLY, never a public route.
 *
 * The Theater page reads the player boxes STORED in the receipt at production time (representativeRunBoxes,
 * lib/simulation-theater/nfl-stored-run-box.mjs). This module re-runs the engine from the moving data/internal input
 * files (role shares, injury captures), which are not BUILD_INPUTS and change after every receipt; importing it from a
 * page would make the page read them (build-input-coverage.test.mjs) and degrade runs to INPUTS_CHANGED. It stays as an
 * audit / test tool: re-deriving a run while its inputs are still current must reproduce the stored box byte for byte.
 *
 * It lives beside the engine, not in lib/simulation-theater/, because it re-runs the engine (the Theater library itself
 * never imports the engine or its RNG: timeline-state.test.mjs purity guard).
 *
 * A receipt's representative runs (`nfl-drive-run@1`) store drives only. The engine that produced them is deterministic
 * and attributes every play to a player, so the run's player box score can be regenerated by re-running the SAME run —
 * but only when that is provably the same run. Two independent checks, both required (fail closed otherwise):
 *
 *   1. INPUTS   the engine's player inputs are rebuilt from the committed files with the shadow build's recipe
 *               (app/scripts/nfl/build-nfl-sim-v2-shadow.mjs: role shares, blocking injuries, active rosters, the
 *               player board's single passer) and hashed exactly as the build hashes them; the hash must equal the one
 *               embedded in the receipt id (`nfl-sim-v2:<event>:<inputHash>`). This proves the player inputs are the ones
 *               the receipt was simulated with. When an input file has moved on since (a later injury capture), the hash
 *               differs and every run of that receipt is INPUTS_CHANGED: no player numbers.
 *   2. FINGERPRINT  the run is re-simulated from the receipt's baseSeed, run index and stored calibration, and its drive
 *               path must equal the stored run's drives exactly (every field of every drive). This proves the seed,
 *               params and calibration reproduce the stored run. A mismatch is FINGERPRINT_MISMATCH.
 *
 * The params file must match the receipt's params sha256 (PARAMS_CHANGED otherwise). Nothing is written; no receipt or
 * data file is modified. The box score itself is lib/simulation-theater/nfl-run-box-score.mjs (pure), cross-checked
 * here against the engine's own accumulators.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import { NFL_SIM_V2_VERSION, N_PERIODS, N_PSTAT, N_TSTAT, PSTAT, TEAM_STAT, compileParams, prepareTeamPlayers, runRng, simulateGame, tiltedTable } from "./engine.mjs";
import { playersFromRoleShares } from "./receipt.mjs";
import { fnv1a64 } from "../../../forecast-ledger/identity.mjs";
import { isBlockingStatus } from "../../injuries/contract.mjs";
import { activeRosterIndex } from "../board-roster-integrity.mjs";
import { safeNflRunBoxScore } from "../../../simulation-theater/nfl-run-box-score.mjs";

export const ROLE_SHARES_REL = "data/internal/research/nfl/role-shares-v1/current.json";
export const INJURIES_REL = "data/internal/research/injuries/nfl/latest.json";
export const ROSTERS_REL = "app/public/data/nfl/rosters/latest.json";
export const PLAYER_BOARD_DIR_REL = "app/public/data/nfl/player-board";

const cache = new Map();
function readOnce(repoRoot, rel, parse = true) {
  const k = `${repoRoot}|${rel}|${parse}`;
  if (!cache.has(k)) {
    let v = null;
    try { const buf = fs.readFileSync(path.join(repoRoot, rel)); v = parse ? JSON.parse(buf.toString("utf8")) : buf; } catch { v = null; }
    cache.set(k, v);
  }
  return cache.get(k);
}

/** The committed availability inputs (blocked ids, active roster index), read once per process. */
export function nflAvailability(repoRoot) {
  const k = `${repoRoot}|availability`;
  if (!cache.has(k)) {
    const inj = readOnce(repoRoot, INJURIES_REL);
    const ros = readOnce(repoRoot, ROSTERS_REL);
    const blocked = new Set((inj?.entries ?? []).filter((e) => e?.athleteId && isBlockingStatus(e.status)).map((e) => `nfl-athlete-${e.athleteId}`));
    cache.set(k, inj && ros ? { blocked, active: activeRosterIndex(ros).active } : null);
  }
  return cache.get(k);
}

/**
 * The engine's player inputs for one event, by the shadow build's recipe. Returns null when an input file is missing.
 * @returns {{ inputs: [{players}, {players}], excluded: [Set, Set] } | null}  index 0 = home, 1 = away
 */
export function nflSimTeamInputs(repoRoot, eventId, homeAbbr, awayAbbr) {
  const role = readOnce(repoRoot, ROLE_SHARES_REL);
  const avail = nflAvailability(repoRoot);
  if (!role || !avail) return null;
  const board = readOnce(repoRoot, `${PLAYER_BOARD_DIR_REL}/${eventId}.json`);
  const side = (abbr) => {
    const block = role.teams?.[abbr] ?? null;
    const onRoster = avail.active.get(abbr);
    const excluded = new Set();
    for (const k of ["passAttempts", "targets", "rushAttempts"]) for (const p of block?.[k]?.players ?? []) if (avail.blocked.has(p.playerId) || (onRoster && !onRoster.has(p.playerId))) excluded.add(p.playerId);
    const qbs = (board?.players ?? []).filter((p) => p.team === abbr && p.markets?.player_pass_yds);
    return { input: playersFromRoleShares(block, excluded, { starterQb: qbs.length === 1 ? qbs[0].playerId : null }), excluded };
  };
  const h = side(homeAbbr);
  const a = side(awayAbbr);
  return { inputs: [h.input, a.input], excluded: [h.excluded, a.excluded] };
}

/** The build's input hash (build-nfl-sim-v2-shadow.mjs), for a receipt's anchors, params and run count. */
export function nflSimInputHash(receipt, inputs) {
  return fnv1a64(JSON.stringify({
    engine: NFL_SIM_V2_VERSION, params: receipt.params?.sha256, anchors: [receipt.calibration?.anchors?.home, receipt.calibration?.anchors?.away], runs: receipt.runCount,
    players: inputs.map((t) => t.players.map((p) => [p.playerId, p.passShare, p.targetShare, p.carryShare, p.catchRate, p.ypr, p.ypc])),
  }));
}

/** Compiled params for a receipt, only when the committed file's sha256 is the receipt's. */
export function compiledFor(repoRoot, receipt) {
  const rel = receipt?.params?.file;
  if (!rel) return null;
  const k = `${repoRoot}|compiled|${rel}`;
  if (!cache.has(k)) {
    const buf = readOnce(repoRoot, rel, false);
    cache.set(k, buf ? { sha: crypto.createHash("sha256").update(buf).digest("hex"), compiled: compileParams(JSON.parse(buf.toString("utf8"))) } : null);
  }
  const c = cache.get(k);
  return c && c.sha === receipt.params.sha256 ? c.compiled : null;
}

const scratchFor = (prep) => ({
  team: [new Float64Array(N_TSTAT), new Float64Array(N_TSTAT)],
  period: [new Float64Array(N_PERIODS), new Float64Array(N_PERIODS)],
  players: [new Float64Array((prep[0].n + 1) * N_PSTAT), new Float64Array((prep[1].n + 1) * N_PSTAT)],
});
const named = (arr, names) => Object.fromEntries(Object.entries(names).map(([k, i]) => [k, arr[i]]));

/**
 * Simulate one run with the play log and return the record nflRunBoxScore folds (with the engine's accumulators for the
 * cross-check). Pure apart from the engine.
 */
export function simulateRunRecord({ compiled, thetas, prep, baseSeed, runIndex, teams, postseason = false }) {
  const tables = [tiltedTable(compiled, thetas[0]), tiltedTable(compiled, thetas[1])];
  const out = scratchFor(prep);
  const drives = [];
  const plays = [];
  const r = simulateGame({ compiled, tables, players: prep, rng: runRng(baseSeed, runIndex), postseason, out, events: drives, plays });
  return {
    runIndex,
    teams,
    slots: [prep[0].slots, prep[1].slots],
    drives,
    plays,
    final: { home: r.score[0], away: r.score[1], overtime: r.ot },
    engine: {
      team: [named(out.team[0], TEAM_STAT), named(out.team[1], TEAM_STAT)],
      players: [0, 1].map((s) => Array.from({ length: prep[s].n + 1 }, (_, slot) => named(out.players[s].subarray(slot * N_PSTAT, (slot + 1) * N_PSTAT), PSTAT))),
    },
  };
}

/**
 * Player box scores for a receipt's stored representative runs.
 * @returns {{ ok: boolean, error: {code, reason}|null, boxes: Record<number, {ok, box, error}> }}
 *   ok false ⇒ no run of this receipt gets player numbers (error says why); otherwise each run is verified on its own.
 */
export function nflRepresentativeRunBoxes(repoRoot, receipt) {
  const fail = (code, reason) => ({ ok: false, error: { code, reason }, boxes: {} });
  const want = String(receipt?.simulationReceiptId ?? "").split(":")[2];
  if (!want || !receipt?.baseSeed || !receipt?.calibration?.thetas) return fail("RECEIPT", "receipt lacks its id hash, seed or calibration");
  const compiled = compiledFor(repoRoot, receipt);
  if (!compiled) return fail("PARAMS_CHANGED", `committed ${receipt?.params?.file} does not match the receipt's params sha256`);
  const ti = nflSimTeamInputs(repoRoot, receipt.eventId, receipt.home.abbr, receipt.away.abbr);
  if (!ti) return fail("INPUTS_MISSING", "role shares, injuries or rosters are not committed");
  const got = nflSimInputHash(receipt, ti.inputs);
  if (got !== want) return fail("INPUTS_CHANGED", `the committed player inputs hash to ${got}, the receipt was simulated with ${want} (availability or role shares changed since); the run cannot be re-derived`);
  const prep = ti.inputs.map(prepareTeamPlayers);
  const teams = { home: { abbr: receipt.home.abbr }, away: { abbr: receipt.away.abbr } };
  const postseason = false; // the shadow build simulates regular-season rules unless seasonType 3; receipts carry no flag, the fingerprint catches a mismatch
  const boxes = {};
  for (const rep of receipt.representativeRuns ?? []) {
    if (boxes[rep.runIndex]) continue; // one run can carry two kinds
    const rec = simulateRunRecord({ compiled, thetas: receipt.calibration.thetas, prep, baseSeed: receipt.baseSeed, runIndex: rep.runIndex, teams, postseason });
    if (JSON.stringify(rec.drives) !== JSON.stringify(rep.drives)) {
      boxes[rep.runIndex] = { ok: false, box: null, error: { code: "FINGERPRINT_MISMATCH", reason: `re-simulated run #${rep.runIndex} does not reproduce the stored drives` } };
      continue;
    }
    boxes[rep.runIndex] = safeNflRunBoxScore(rec);
  }
  return { ok: true, error: null, boxes };
}

/** The display boxes only ({ [runIndex]: box } for verified runs) and the per-run refusals. */
export function verifiedRunBoxes(res) {
  const boxes = {};
  const refusals = {};
  for (const [k, v] of Object.entries(res?.boxes ?? {})) {
    if (v.ok) boxes[k] = v.box; else refusals[k] = v.error;
  }
  return { boxes, refusals, error: res?.ok ? null : res?.error ?? null };
}
