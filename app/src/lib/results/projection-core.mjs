/**
 * THE CANONICAL RESULTS PROJECTION — pure assembly, no IO (v1.8 · Track C · C1).
 *
 * docs/V19_RESULTS_TRUST_ARCHITECTURE.md §2 names the target: ONE read model over the settlement owners,
 * ONE builder, ONE reader. This file is the assembly. `scripts/results/build-results-projection.mjs`
 * reads the owners from disk and writes the artifact; `lib/results/projection.ts` reads the artifact for
 * pages. Nothing here reads a file, and nothing here grades, prices or forecasts.
 *
 * WHAT A CELL IS. One graded population, from ONE owner, in ONE typed era, with its own window and its
 * own count semantics. The projection stores no number an owner does not already carry: every count is
 * copied, every `n` is the sum of the counts the owner carries, every window is the owner's own dates.
 * A cell without an owner is not emitted — a consumer that finds no cell prints nothing, never "0–0".
 *
 * THE SEVEN RULES (V19 §2), each pinned by a test in projection-core.test.mjs:
 *   1. never a forecast, never a probability — only graded outcomes and owner STATES;
 *   2. no mega-record — families stay separate and `sumSameEra` refuses to cross them;
 *   3. every cell carries window, n, era, owner path + generatedAt; absent owner ⇒ absent cell;
 *   4. pending is a count, never a loss; push and void are counts, never decisive;
 *   5. eras are typed, never blended silently — a blended figure carries its composition beside it;
 *   6. one reader (projection.ts); the fallback is "no figure";
 *   7. write-once, dated (the builder refuses to rewrite a dated file that differs).
 *
 * HARD RULES this file enforces at construction: pending is never a loss; missing is never zero
 * (`null`, never `0`, for a count the owner does not carry); a recorded zero is a zero; push/void are
 * first-class; a product record is not a forecast record; cycle completion is not a leg hit rate; a
 * calibration state is a word, not a number; two eras are never summed by any exported helper.
 */

export const PROJECTION_SCHEMA = "gtp.results-projection.v1";
export const PROJECTION_REL = "results/projection";

/** What kind of number the cell is (V19 §4, one word per thing). Closed. */
export const RECORD_TYPES = Object.freeze({
  PRODUCT_RECORD: "PRODUCT_RECORD",       // settled cards or lanes W–L per product
  FORECAST_RECORD: "FORECAST_RECORD",     // graded model leans, decisive = won + lost, with n
  LAB_CARD_RECORD: "LAB_CARD_RECORD",     // Parlay Lab paper cards, whole-card W–L
  CYCLE_COMPLETION: "CYCLE_COMPLETION",   // ladders completed / lost / open — never a W–L
  CALIBRATION_STATE: "CALIBRATION_STATE", // a model family's state word + n — never a number
  ERA_GAP: "ERA_GAP",                     // a disclosed hole in an owner's coverage — counts null
});

