/**
 * Assemble the projection from the owners. `sources` is a map of owner key → { path, doc } (null or
 * absent when the file is missing). Pure and deterministic for a given `now`.
 */
export function buildProjection(sources, { now }) {
  if (!now || !Number.isFinite(Date.parse(now))) throw new Error("projection: builtAt (`now`) must be an ISO timestamp");
  for (const k of REQUIRED_OWNERS) if (!sources?.[k]?.doc) throw new Error(`projection: REFUSED — required owner "${k}" is missing`);

  const cells = [];
  const seen = new Map();
  const push = (cell) => {
    if (seen.has(cell.cellId)) throw new Error(`projection: REFUSED — duplicate owner conflict: two cells claim ${cell.cellId} (${seen.get(cell.cellId)} and ${cell.owner.path})`);
    seen.set(cell.cellId, cell.owner.path);
    cells.push(cell);
  };
  productCells(sources, push);
  forecastCells(sources, push);
  labCells(sources, push);
  cycleCells(sources, push);
  modelFamilyCells(sources, push);

  /* Headlines: ONE cell per family, never a legacy era, never a total. */
  const find = (pred) => cells.find(pred)?.cellId ?? null;
  const byFamily = {
    [FAMILIES.PRODUCT]: find((c) => c.product === "bank-builder" && c.segment === "protected-record" && !LEGACY_ERAS.includes(c.era)),
    [FAMILIES.FORECAST]: find((c) => c.family === FAMILIES.FORECAST && c.sport === "mlb" && c.segment === "lifetime-summary") ?? find((c) => c.family === FAMILIES.FORECAST && c.sport === "mlb"),
    [FAMILIES.LAB]: find((c) => c.family === FAMILIES.LAB && c.segment === "risk-ladder-overall"),
    [FAMILIES.CYCLE]: null,        // a table, never a headline figure
    [FAMILIES.MODEL_FAMILY]: null, // state words, never a headline figure
  };
  const byProduct = {
    "bank-builder": byFamily[FAMILIES.PRODUCT],
    moonshot: find((c) => c.product === "moonshot" && c.era === ERAS.RECEIPT_ERA && c.family === FAMILIES.PRODUCT),
    "parlay-lab": byFamily[FAMILIES.LAB],
  };
  const bySport = {};
  for (const s of ["mlb", "nfl", "ufc", "epl", "nba"]) {
    bySport[s] = find((c) => c.family === FAMILIES.FORECAST && c.sport === s && c.segment === "lifetime-summary") ?? find((c) => c.family === FAMILIES.FORECAST && c.sport === s) ?? null;
  }
  for (const [k, id] of Object.entries(byFamily)) {
    const cell = id ? cells.find((c) => c.cellId === id) : null;
    if (cell && LEGACY_ERAS.includes(cell.era)) throw new Error(`projection: REFUSED — headline for ${k} would be a legacy era`);
  }

  const sourceList = Object.entries(sources).filter(([k]) => k !== "receipts").map(([key, s]) => ({
    key, present: Boolean(s?.doc), path: s?.path ?? null, generatedAt: s?.doc ? (strOrNull(s.doc.generatedAt) ?? strOrNull(s.doc.bankedAt) ?? strOrNull(s.doc.protectedFold?.foldedAt) ?? null) : null,
  }));
  const gpIndex = sourceList.findIndex((s) => s.key === "gradedPicks");
  if (gpIndex >= 0) {
    sourceList.splice(gpIndex, 1, ...Object.entries(sources.gradedPicks ?? {}).map(([sport, g]) => ({ key: `gradedPicks.${sport}`, present: Boolean(g?.doc), path: g?.path ?? null, generatedAt: strOrNull(g?.doc?.generatedAt) })));
  }
  const receipts = sources.receipts ?? [];
  sourceList.push({ key: "receipts", present: receipts.length > 0, path: "mr-dub/settled/<date>.json", generatedAt: receipts.map((r) => r.doc?.settledAt).filter(Boolean).sort().at(-1) ?? null, count: receipts.length });

  return {
    schema: PROJECTION_SCHEMA,
    artifact: "results-projection",
    dataClass: "PUBLIC_DERIVED",
    builtAt: now,
    rules: {
      pending: "a count, never a loss, never inside a W–L",
      pushVoid: "counts beside the record, never decisive",
      missing: "null — a count the owner does not carry is never 0; a recorded 0 is a 0",
      eras: "typed; two eras are never summed; a COMPOSITE cell carries its composition; no cross-family total exists or may be derived",
      forecasts: "none — this projection owns no probability and no forecast",
    },
    sources: sourceList,
    headline: { byFamily, byProduct, bySport },
    cells,
  };
}

/** Structural validation of an artifact read from disk (the reader's contract). Throws with the first defect. */
export function assertProjectionShape(p) {
  if (!p || p.schema !== PROJECTION_SCHEMA) throw new Error(`projection: schema ${p?.schema} ≠ ${PROJECTION_SCHEMA}`);
  if (!Array.isArray(p.cells)) throw new Error("projection: cells must be an array");
  const ids = new Set();
  for (const c of p.cells) {
    if (ids.has(c.cellId)) throw new Error(`projection: duplicate cellId ${c.cellId}`);
    ids.add(c.cellId);
    if (!Object.values(ERAS).includes(c.era)) throw new Error(`projection: ${c.cellId} era untyped`);
    if (!Object.values(FAMILIES).includes(c.family)) throw new Error(`projection: ${c.cellId} family unknown`);
    if (!c.owner?.path) throw new Error(`projection: ${c.cellId} has no owner`);
    if (!c.window || !("from" in c.window) || !("to" in c.window)) throw new Error(`projection: ${c.cellId} has no window`);
    counts(c.counts);
    if (c.era === ERAS.COMPOSITE && !Array.isArray(c.composition)) throw new Error(`projection: ${c.cellId} is COMPOSITE without composition`);
  }
  const h = p.headline ?? {};
  for (const block of [h.byFamily, h.byProduct, h.bySport]) for (const k of Object.keys(block ?? {})) {
    if (/^(total|overall|all|combined)$/i.test(k)) throw new Error(`projection: headline slot "${k}" would be a cross-family total`);
    if (block[k] !== null && !ids.has(block[k])) throw new Error(`projection: headline ${k} points at a missing cell ${block[k]}`);
  }
  return true;
}
