/**
 * Typed eras. The first nine are V19 §2 rule 5 / V17 §8. Three are added because an owner needs them:
 *   COMPOSITE          — a blended figure the owner itself publishes (portfolio.record = July base +
 *                        Rule S fold). Allowed ONLY with `composition` beside it; never an input to a sum.
 *   LIVE_LEDGER        — a forecast or calibration owner that is regenerated by a wired settler and has
 *                        no policy or era split inside its window. Forcing these into RECEIPT_ERA would
 *                        claim they are part of the Rule S receipt population; they are not.
 *   UNSEGMENTED_WINDOW — an owner whose window spans a typed boundary (the Lab's 2026-08-17 policy
 *                        change) and does not segment its record. It can be shown only with its window
 *                        printed, and it is never an input to a sum.
 */
export const ERAS = Object.freeze({
  PROTECTED_BASE: "PROTECTED_BASE",
  RECEIPT_ERA: "RECEIPT_ERA",
  UNRECEIPTED_GAP: "UNRECEIPTED_GAP",
  LEDGER_ONLY: "LEDGER_ONLY",
  HISTORICAL_ONLY: "HISTORICAL_ONLY",
  POLICY_V1: "POLICY_V1",
  POLICY_V2: "POLICY_V2",
  PENDING_SETTLEMENT: "PENDING_SETTLEMENT",
  LEGACY_PRODUCT_LEDGER: "LEGACY_PRODUCT_LEDGER",
  COMPOSITE: "COMPOSITE",
  LIVE_LEDGER: "LIVE_LEDGER",
  UNSEGMENTED_WINDOW: "UNSEGMENTED_WINDOW",
});

/** Eras that are already a sum, or cannot be segmented — never an input to `sumSameEra`. */
export const UNSUMMABLE_ERAS = Object.freeze([ERAS.COMPOSITE, ERAS.UNSEGMENTED_WINDOW]);

/** Eras a headline may never be drawn from unless a caller asks for that era by name. */
export const LEGACY_ERAS = Object.freeze([
  ERAS.LEGACY_PRODUCT_LEDGER, ERAS.LEDGER_ONLY, ERAS.HISTORICAL_ONLY, ERAS.POLICY_V1, ERAS.PROTECTED_BASE,
]);

/** Cell status. Closed. */
export const STATUSES = Object.freeze({
  LIVE: "LIVE",                       // the owner is regenerated by a scheduled writer
  FROZEN: "FROZEN",                   // the owner has no writer; history
  DISCLOSED_GAP: "DISCLOSED_GAP",     // an ERA_GAP cell
  PENDING: "PENDING",                 // placed, awaiting a receipt
  SUPERSEDED: "SUPERSEDED",           // an earlier snapshot of a population a later owner restates
  WINDOW_CONTRADICTS_LABEL: "WINDOW_CONTRADICTS_LABEL", // the owner's label names a window its dates exceed
  OWNERS_DISAGREE: "OWNERS_DISAGREE", // two owners of one population carry different counts
});

const COUNT_KEYS = Object.freeze(["won", "lost", "pending", "push", "void"]);
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

const isInt = (v) => Number.isInteger(v);
const intOrNull = (v) => (isInt(v) ? v : null);
const strOrNull = (v) => (typeof v === "string" && v.length ? v : null);
const numOrNull = (v) => (typeof v === "number" && Number.isFinite(v) ? v : null);

/** A count block. `null` means "the owner does not carry this" — never 0. */
export function counts({ won = null, lost = null, pending = null, push = null, void: v = null } = {}) {
  const out = { won, lost, pending, push, void: v };
  for (const k of COUNT_KEYS) {
    if (out[k] !== null && !isInt(out[k])) throw new Error(`projection: count "${k}" must be an integer or null (got ${JSON.stringify(out[k])})`);
    if (out[k] !== null && out[k] < 0) throw new Error(`projection: count "${k}" cannot be negative`);
  }
  return out;
}

/** n = the settled items the owner carries: won + lost + push + void over the NUMERIC keys. Pending is never inside. */
export function settledN(c) {
  const keys = ["won", "lost", "push", "void"].filter((k) => isInt(c?.[k]));
  return keys.length ? keys.reduce((s, k) => s + c[k], 0) : null;
}

const dayShift = (iso, days) => {
  if (!DATE_RE.test(iso ?? "")) return null;
  const d = new Date(`${iso}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
};

/** Cell identity — family, sport, product, era, segment. Two cells with one id is a duplicate-owner conflict. */
export function cellIdOf({ family, sport, product, era, segment }) {
  return [family, sport ?? "-", product ?? "-", era, segment ?? "-"].join(":");
}

/**
 * Construct one cell. Validates the closed enums and the shape; refuses a cell without an owner path,
 * a cell whose era is not typed, or a COMPOSITE cell without its composition. Every field a consumer
 * may read is present on every cell (null where the owner carries nothing).
 */
export function makeCell(spec) {
  const {
    recordType, family, sport = null, product = null, market = null, segment = null,
    modelOrPolicyVersion = null, era, counts: c, owner, window, status,
    displayEligible, semantics, composition = null, hitRate = null, ownerState = null,
    cycles = null, crossCheck = null, sameAs = null,
  } = spec;
  if (!Object.values(RECORD_TYPES).includes(recordType)) throw new Error(`projection: unknown recordType ${recordType}`);
  if (!Object.values(FAMILIES).includes(family)) throw new Error(`projection: unknown family ${family}`);
  if (!Object.values(ERAS).includes(era)) throw new Error(`projection: era must be one of the typed eras (got ${JSON.stringify(era)})`);
  if (!Object.values(STATUSES).includes(status)) throw new Error(`projection: unknown status ${status}`);
  if (!owner || typeof owner.path !== "string" || !owner.path) throw new Error(`projection: a cell without an owner path is not emitted (${family}/${product ?? sport})`);
  if (!("generatedAt" in owner)) throw new Error(`projection: owner.generatedAt must be present (null when the owner carries no stamp)`);
  if (!window || !("from" in window) || !("to" in window)) throw new Error(`projection: every cell carries a window {from, to}`);
  for (const k of ["from", "to"]) if (window[k] !== null && !DATE_RE.test(window[k])) throw new Error(`projection: window.${k} must be YYYY-MM-DD or null`);
  if (!displayEligible || typeof displayEligible.eligible !== "boolean" || typeof displayEligible.reason !== "string") throw new Error("projection: displayEligible needs {eligible: boolean, reason: string}");
  if (typeof semantics !== "string" || !semantics) throw new Error("projection: every cell names its semantics");
  const cc = counts(c ?? {});
  const n = spec.n === undefined ? settledN(cc) : intOrNull(spec.n);
  if (era === ERAS.COMPOSITE) {
    if (!Array.isArray(composition) || composition.length < 2) throw new Error("projection: a COMPOSITE cell must carry the era composition beside it");
    for (const part of composition) {
      if (!Object.values(ERAS).includes(part.era) || UNSUMMABLE_ERAS.includes(part.era)) throw new Error(`projection: composition part era ${part.era} is not a summable typed era`);
      counts(part.counts);
    }
    for (const k of COUNT_KEYS) {
      if (!composition.every((p) => isInt(p.counts[k]))) continue; // a part the owner does not carry cannot be checked
      const sum = composition.reduce((s, p) => s + p.counts[k], 0);
      if (cc[k] !== sum) throw new Error(`projection: COMPOSITE ${k} ${cc[k]} ≠ Σ composition ${sum}`);
    }
  } else if (composition) {
    throw new Error("projection: only a COMPOSITE cell carries a composition");
  }
  if (recordType === RECORD_TYPES.CALIBRATION_STATE) {
    if (COUNT_KEYS.some((k) => cc[k] !== null) || hitRate !== null) throw new Error("projection: a CALIBRATION_STATE cell carries a state word and n only");
  }
  if (recordType === RECORD_TYPES.ERA_GAP && (COUNT_KEYS.some((k) => cc[k] !== null) || n !== null)) throw new Error("projection: an ERA_GAP cell carries no counts");
  const cell = {
    cellId: cellIdOf({ family, sport, product, era, segment }),
    recordType, family, recordFamilyId: RECORD_FAMILY_ID[family] ?? null,
    sport, product, market, segment, modelOrPolicyVersion, era,
    n, counts: cc, decisive: isInt(cc.won) && isInt(cc.lost) ? cc.won + cc.lost : null,
    hitRate: numOrNull(hitRate), ownerState,
    owner: { path: owner.path, generatedAt: owner.generatedAt ?? null, stampField: owner.stampField ?? "generatedAt" },
    window: { from: window.from ?? null, to: window.to ?? null },
    status, displayEligible: { eligible: displayEligible.eligible, reason: displayEligible.reason },
    semantics,
    composition: composition ? composition.map((p) => ({ era: p.era, cellId: p.cellId ?? null, counts: counts(p.counts), window: p.window ?? null })) : null,
    cycles, crossCheck, sameAs,
  };
  return cell;
}

/* ── labels ─────────────────────────────────────────────────────────────────────────────────────── */

const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`;

/**
 * "W–L" from a count block, with push and void appended as counts. Pending is NEVER inside the W–L and
 * never appended here — it is a separate figure a surface prints beside the record. Returns null when
 * won or lost is not carried (a label cannot be built from a missing count).
 */
export function formatRecordLabel(c) {
  if (!c || !isInt(c.won) || !isInt(c.lost)) return null;
  let label = `${c.won}–${c.lost}`;
  if (isInt(c.push) && c.push > 0) label += ` · ${plural(c.push, "push", "pushes")}`;
  if (isInt(c.void) && c.void > 0) label += ` · ${plural(c.void, "void", "voids")}`;
  return label;
}

/**
 * The C9 rule. A label ONLY when a cell exists, carries won and lost, and is display-eligible; otherwise
 * null — never "0–0", never a fallback figure from another cell. A recorded 0–0 stays a recorded 0–0 in
 * `counts`; whether it may be SHOWN is the owner's own rule, carried in `displayEligible`.
 */
export function recordLabelOrNull(cell) {
  if (!cell || !cell.counts || !cell.displayEligible?.eligible) return null;
  if (cell.recordType === RECORD_TYPES.CYCLE_COMPLETION || cell.recordType === RECORD_TYPES.CALIBRATION_STATE || cell.recordType === RECORD_TYPES.ERA_GAP) return null;
  return formatRecordLabel(cell.counts);
}

/** "N pending" or null when the cell does not carry pending. Never folded into the record label. */
export function pendingLabelOrNull(cell) {
  if (!cell || !isInt(cell.counts?.pending)) return null;
  return `${cell.counts.pending} pending`;
}

/* ── selectors ──────────────────────────────────────────────────────────────────────────────────── */

export const cellsOf = (p) => (Array.isArray(p?.cells) ? p.cells : []);
export const cellById = (p, id) => cellsOf(p).find((c) => c.cellId === id) ?? null;
export const cellsByFamily = (p, family) => cellsOf(p).filter((c) => c.family === family);
export const cellsBySport = (p, sport) => cellsOf(p).filter((c) => c.sport === sport);
export const cellsByProduct = (p, product) => cellsOf(p).filter((c) => c.product === product);

/**
 * The designated headline cell for a family, or null. A legacy era is never a headline; to read one, a
 * caller names it with `cellForEra` — a request by era, never a fallback.
 */
export function headlineFor(p, family) {
  const id = p?.headline?.byFamily?.[family] ?? null;
  const cell = id ? cellById(p, id) : null;
  if (cell && LEGACY_ERAS.includes(cell.era)) throw new Error(`projection: headline for ${family} points at a legacy era (${cell.era}) — a legacy era is read only by explicit request`);
  return cell;
}
export function headlineForProduct(p, product) {
  const id = p?.headline?.byProduct?.[product] ?? null;
  const cell = id ? cellById(p, id) : null;
  if (cell && LEGACY_ERAS.includes(cell.era)) throw new Error(`projection: product headline for ${product} points at a legacy era (${cell.era})`);
  return cell;
}
export function headlineForSport(p, sport) {
  const id = p?.headline?.bySport?.[sport] ?? null;
  return id ? cellById(p, id) : null;
}
/** Explicit era request — the only way a legacy era reaches a surface. */
/**
 * An explicit era request — the only way a legacy era reaches a surface.
 *
 * The JSDoc types are load-bearing, not decoration: this module is untyped `.mjs`, so without them
 * TypeScript infers each selector as `null | undefined` from its `= null` default and the typed reader
 * in projection.ts cannot pass a string. `tsc --noEmit` failed on exactly that before these were added.
 *
 * @param {object | null} p
 * @param {{ family: string, era: string, product?: string | null, sport?: string | null, segment?: string | null }} q
 * @returns {object | null}
 */
export function cellForEra(p, { family, era, product = null, sport = null, segment = null }) {
  if (!Object.values(ERAS).includes(era)) throw new Error(`projection: cellForEra needs a typed era (got ${JSON.stringify(era)})`);
  return cellsOf(p).find((c) => c.family === family && c.era === era && (product === null || c.product === product) && (sport === null || c.sport === sport) && (segment === null || c.segment === segment)) ?? null;
}

/**
 * Sum cells of ONE family in ONE summable era. The only aggregation this module exports, and it throws
 * on anything else: mixed families, mixed eras, a missing era, a COMPOSITE or UNSEGMENTED input, a
 * non-summable record type. A count that any input does not carry is null in the sum — never 0.
 */
export function sumSameEra(cells) {
  if (!Array.isArray(cells) || cells.length === 0) return null;
  const families = new Set(cells.map((c) => c.family));
  if (families.size > 1) throw new Error(`projection: refusing to sum across families (${[...families].join(", ")}) — they are different populations`);
  const eras = new Set(cells.map((c) => c.era));
  if (cells.some((c) => !Object.values(ERAS).includes(c.era))) throw new Error("projection: refusing to sum a cell with no typed era");
  if (eras.size > 1) throw new Error(`projection: refusing to sum across eras (${[...eras].join(", ")}) — incomparable populations`);
  const era = [...eras][0];
  if (UNSUMMABLE_ERAS.includes(era)) throw new Error(`projection: ${era} cells are already a sum or cannot be segmented — not an input to a sum`);
  const types = new Set(cells.map((c) => c.recordType));
  if (types.size > 1) throw new Error(`projection: refusing to sum across record types (${[...types].join(", ")})`);
  const type = [...types][0];
  if (![RECORD_TYPES.PRODUCT_RECORD, RECORD_TYPES.FORECAST_RECORD, RECORD_TYPES.LAB_CARD_RECORD].includes(type)) throw new Error(`projection: ${type} cells are not summable`);
  const out = {};
  for (const k of COUNT_KEYS) out[k] = cells.every((c) => isInt(c.counts?.[k])) ? cells.reduce((s, c) => s + c.counts[k], 0) : null;
  const froms = cells.map((c) => c.window?.from).filter(Boolean).sort();
  const tos = cells.map((c) => c.window?.to).filter(Boolean).sort();
  return {
    family: [...families][0], era, recordType: type,
    counts: counts(out), n: settledN(out),
    window: { from: froms[0] ?? null, to: tos.at(-1) ?? null },
    cells: cells.map((c) => c.cellId),
  };
}

/* ── the owners → cells ─────────────────────────────────────────────────────────────────────────── */

const PLACED = new Set(["active", "won", "lost", "void", "push"]);
const DECIDED = new Set(["won", "lost", "void", "push"]);
const isWin = (o) => /^w(on|in)?$/i.test(String(o ?? ""));
const isLoss = (o) => /^los[ts]$/i.test(String(o ?? ""));

/** Owners the projection cannot be built without. Everything else is optional: absent owner ⇒ absent cells. */
export const REQUIRED_OWNERS = Object.freeze(["portfolio"]);

const eligible = (reason) => ({ eligible: true, reason });
const ineligible = (reason) => ({ eligible: false, reason });

function productCells(src, push) {
  const { portfolio, receipts = [], bankedLadders, moonshotLedger } = src;
  const pf = portfolio.doc;
  const fold = pf.protectedFold ?? null;
  const base = fold?.base ?? null;
  const ownerStamp = { path: portfolio.path, generatedAt: fold?.foldedAt ?? pf.generatedAt ?? null, stampField: fold?.foldedAt ? "protectedFold.foldedAt" : "generatedAt" };
  const foldDays = Array.isArray(fold?.days) ? fold.days : [];
  const foldFrom = foldDays[0]?.date ?? null;
  const foldThrough = fold?.foldedThrough ?? null;

  /* Receipts through the fold — the settlement owner's own tally under the fold's PLACED rule. Used as a
     cross-check on the record owner, never as a second record: a disagreement is corruption and refuses. */
  const receiptTally = (product) => {
    const inScope = receipts.filter((r) => r.doc?.date && (!foldThrough || r.doc.date <= foldThrough) && (!base?.asOf || r.doc.date > base.asOf));
    let won = 0, lost = 0, voids = 0, pushes = 0;
    for (const r of inScope) for (const l of r.doc.lanes ?? []) {
      if (l.product !== product) continue;
      const placed = l.status != null ? PLACED.has(String(l.status)) : DECIDED.has(String(l.result ?? "pending"));
      if (!placed) continue;
      if (l.result === "won") won += 1; else if (l.result === "lost") lost += 1; else if (l.result === "void") voids += 1; else if (l.result === "push") pushes += 1;
    }
    return inScope.length ? { won, lost, void: voids, push: pushes, receipts: inScope.length, source: "mr-dub/settled/<date>.json" } : null;
  };

  const bbFold = { won: foldDays.reduce((s, d) => s + (d.bankBuilder?.won ?? 0), 0), lost: foldDays.reduce((s, d) => s + (d.bankBuilder?.lost ?? 0), 0) };
  const msFold = { won: foldDays.reduce((s, d) => s + (d.moonshot?.won ?? 0), 0), lost: foldDays.reduce((s, d) => s + (d.moonshot?.lost ?? 0), 0) };

  const baseCell = base?.record ? makeCell({
    recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product: "bank-builder",
    era: ERAS.PROTECTED_BASE, modelOrPolicyVersion: null,
    counts: { won: intOrNull(base.record.wins), lost: intOrNull(base.record.losses), pending: intOrNull(base.record.pending), push: null, void: intOrNull(base.record.voids) },
    owner: { ...ownerStamp, path: portfolio.path }, window: { from: strOrNull(pf.startingDate), to: strOrNull(base.asOf) },
    status: STATUSES.FROZEN,
    displayEligible: eligible("era component of the protected record — shown beside the composite as its base, never alone as the current record"),
    semantics: "The July-7 protected base (multi-sport operator era). Frozen in protected-fold.mjs PROTECTED_BASE; only won/lost enter W–L; voids carried by the owner; push not carried.",
  }) : null;
  if (baseCell) push(baseCell);

  const bbReceipt = fold ? makeCell({
    recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product: "bank-builder",
    era: ERAS.RECEIPT_ERA, modelOrPolicyVersion: `Rule ${fold.rule ?? "S"}`,
    counts: { won: bbFold.won, lost: bbFold.lost, pending: null, push: null, void: null },
    owner: ownerStamp, window: { from: foldFrom, to: foldThrough },
    status: STATUSES.LIVE,
    displayEligible: eligible("era component of the protected record — the Rule S fold of the nightly receipts"),
    semantics: "Σ protectedFold.days bankBuilder.won/lost. A day folds only when every PLACED lane is decided; pending is never inside. The fold tallies won and lost only (void/push not carried here; the receipts carry them in crossCheck).",
    crossCheck: receiptTally("bank-builder"),
  }) : null;
  if (bbReceipt) {
    if (bbReceipt.crossCheck && (bbReceipt.crossCheck.won !== bbFold.won || bbReceipt.crossCheck.lost !== bbFold.lost)) {
      throw new Error(`projection: REFUSED — the Rule S fold (${bbFold.won}-${bbFold.lost}) disagrees with the receipts through ${foldThrough} (${bbReceipt.crossCheck.won}-${bbReceipt.crossCheck.lost}) for bank-builder; the record owner and the settlement owner must agree`);
    }
    push(bbReceipt);
  }

  if (pf.record && isInt(pf.record.wins) && isInt(pf.record.losses)) {
    const composition = baseCell && bbReceipt ? [
      { era: ERAS.PROTECTED_BASE, cellId: baseCell.cellId, counts: baseCell.counts, window: baseCell.window },
      { era: ERAS.RECEIPT_ERA, cellId: bbReceipt.cellId, counts: bbReceipt.counts, window: bbReceipt.window },
    ] : null;
    push(makeCell({
      recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product: "bank-builder",
      segment: "protected-record",
      era: composition ? ERAS.COMPOSITE : ERAS.PROTECTED_BASE, modelOrPolicyVersion: composition ? `Rule ${fold.rule ?? "S"}` : null,
      counts: { won: pf.record.wins, lost: pf.record.losses, pending: intOrNull(pf.record.pending), push: null, void: intOrNull(pf.record.voids) },
      owner: ownerStamp, window: { from: strOrNull(pf.startingDate), to: foldThrough ?? strOrNull(base?.asOf) },
      status: composition ? STATUSES.LIVE : STATUSES.FROZEN,
      displayEligible: composition ? eligible("the protected Bank Builder record; a blended figure shown only with its era composition beside it") : ineligible("no fold on the owner — the record has no era composition to show beside it"),
      semantics: "portfolio.record — the official Bank Builder paper record (July base + Rule S fold). Only won/lost enter W–L; pending 0 by construction of the fold; voids carried; push not carried by the owner. Bank Builder only: Moonshot's record is on its own line.",
      composition,
    }));
  }

  /* The record hole between the base and the fold: disclosed as a gap, counts null. Derived from the
     owner's own dates (base.asOf + 1 → fold.days[0] − 1), never hardcoded. */
  if (base?.asOf && foldFrom) {
    const gapFrom = dayShift(base.asOf, 1), gapTo = dayShift(foldFrom, -1);
    if (gapFrom && gapTo && gapFrom <= gapTo) push(makeCell({
      recordType: RECORD_TYPES.ERA_GAP, family: FAMILIES.PRODUCT, sport: null, product: "bank-builder",
      era: ERAS.UNRECEIPTED_GAP, counts: {}, n: null,
      owner: ownerStamp, window: { from: gapFrom, to: gapTo },
      status: STATUSES.DISCLOSED_GAP,
      displayEligible: eligible("a disclosed gap — render as a gap in the timeline, never as a number"),
      semantics: "No receipt and no fold day covers these dates (V19 C8). The July base closes at protectedFold.base.asOf; the first folded receipt is protectedFold.days[0]. Whatever was placed in between is not in the protected record and is not reconstructed here.",
    }));
  }

  /* Placed lanes still awaiting a receipt, from the receipts themselves (after the fold, or the halted day). */
  if (receipts.length && foldThrough) {
    const after = receipts.filter((r) => r.doc?.date && r.doc.date > foldThrough);
    for (const product of ["bank-builder", "moonshot"]) {
      let pending = 0;
      for (const r of after) for (const l of r.doc.lanes ?? []) {
        if (l.product !== product) continue;
        const placed = l.status != null ? PLACED.has(String(l.status)) : false;
        if (placed && String(l.result ?? "pending") === "pending") pending += 1;
      }
      const newest = receipts.map((r) => r.doc?.date).filter(Boolean).sort().at(-1) ?? null;
      push(makeCell({
        recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product,
        era: ERAS.PENDING_SETTLEMENT, counts: { pending }, n: null,
        owner: { path: "mr-dub/settled/<date>.json", generatedAt: receipts.find((r) => r.doc?.date === newest)?.doc?.settledAt ?? null, stampField: "settledAt" },
        window: { from: after.length ? after.map((r) => r.doc.date).sort()[0] : foldThrough, to: newest },
        status: STATUSES.PENDING,
        displayEligible: eligible("a pending count — never inside a W–L"),
        semantics: "Placed lanes (status active) whose receipt result is still pending, on receipts dated after protectedFold.foldedThrough. Today's placed lanes live in mr-dub/daily-portfolio.json, which is not an owner of this projection. Pending is never a loss.",
      }));
    }
  }

  /* Moonshot — receipt/fold era from the portfolio's own line. */
  const ms = pf.moonshot ?? null;
  const foldEra = typeof ms?.inBankrollSince === "string" && DATE_RE.test(ms.inBankrollSince);
  if (ms?.record && foldEra) {
    const cell = makeCell({
      recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product: "moonshot",
      era: ERAS.RECEIPT_ERA, modelOrPolicyVersion: `Rule ${fold?.rule ?? "S"}`,
      counts: { won: intOrNull(ms.record.wins), lost: intOrNull(ms.record.losses), pending: intOrNull(ms.record.pending), push: null, void: intOrNull(ms.record.voids) },
      owner: ownerStamp, window: { from: ms.inBankrollSince, to: foldThrough },
      status: STATUSES.LIVE,
      displayEligible: eligible("the current Moonshot record — settled receipts since the product entered the protected bankroll"),
      semantics: "portfolio.moonshot.record — every Moonshot lane settled since inBankrollSince, graded nightly from the official box score, folded under Rule S. Kept on its own line; never summed with Bank Builder and never with the June legacy ledger.",
      crossCheck: receiptTally("moonshot"),
    });
    if (cell.crossCheck && (cell.crossCheck.won !== msFold.won || cell.crossCheck.lost !== msFold.lost)) {
      throw new Error(`projection: REFUSED — the Rule S fold (${msFold.won}-${msFold.lost}) disagrees with the receipts through ${foldThrough} (${cell.crossCheck.won}-${cell.crossCheck.lost}) for moonshot`);
    }
    if (isInt(ms.record.wins) && isInt(ms.record.losses) && (ms.record.wins !== msFold.won || ms.record.losses !== msFold.lost)) {
      throw new Error(`projection: REFUSED — portfolio.moonshot.record ${ms.record.wins}-${ms.record.losses} ≠ Σ protectedFold.days moonshot ${msFold.won}-${msFold.lost}`);
    }
    push(cell);
  }
  /* The single pre-fold card inside the July base (portfolio.moonshot.legacy, or a pre-fold .moonshot block). */
  const legacyBlock = foldEra ? ms?.legacy ?? null : ms ?? null;
  if (legacyBlock?.record && isInt(legacyBlock.record.wins) && isInt(legacyBlock.record.losses)) {
    push(makeCell({
      recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product: "moonshot", segment: "legacy-card",
      era: ERAS.PROTECTED_BASE, counts: { won: legacyBlock.record.wins, lost: legacyBlock.record.losses, pending: intOrNull(legacyBlock.record.pending), push: null, void: intOrNull(legacyBlock.record.voids) },
      owner: ownerStamp, window: { from: null, to: strOrNull(base?.asOf) ?? strOrNull(pf.generatedAt?.slice?.(0, 10)) },
      status: STATUSES.FROZEN,
      displayEligible: ineligible("a single pre-fold card kept inside the July base as history — not a product record"),
      semantics: "portfolio.moonshot.legacy.record — the one stopped Moonshot card of the July-7 base. The owner carries no start date for it (window.from null).",
    }));
  }
  /* The June 2026 product ledger — the LEGACY era, its own cell, never merged with the fold era. */
  if (moonshotLedger?.doc && Array.isArray(moonshotLedger.doc.results)) {
    const rows = moonshotLedger.doc.results;
    const won = rows.filter((r) => isWin(r?.outcome)).length;
    const lost = rows.filter((r) => isLoss(r?.outcome)).length;
    const dates = rows.map((r) => r?.date).filter((d) => DATE_RE.test(d ?? "")).sort();
    push(makeCell({
      recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product: "moonshot",
      era: ERAS.LEGACY_PRODUCT_LEDGER, counts: { won, lost, pending: rows.length - won - lost, push: null, void: null },
      owner: { path: moonshotLedger.path, generatedAt: strOrNull(moonshotLedger.doc.generatedAt), stampField: "generatedAt" },
      window: { from: dates[0] ?? null, to: dates.at(-1) ?? null },
      status: STATUSES.FROZEN,
      displayEligible: eligible("the June 2026 legacy era — labelled as legacy, never the current headline, never summed with the receipt era"),
      semantics: "product-ledger/moonshot.json rows counted by outcome (the same rule moonshot-state.mjs and read-model.mjs use): won/lost by outcome word, an undecided row is pending. No wired settler; a closed ledger.",
    }));
    /* Moonshot's own coverage hole: ledger end + 1 → inBankrollSince − 1. */
    if (foldEra && dates.length) {
      const gapFrom = dayShift(dates.at(-1), 1), gapTo = dayShift(ms.inBankrollSince, -1);
      if (gapFrom && gapTo && gapFrom <= gapTo) push(makeCell({
        recordType: RECORD_TYPES.ERA_GAP, family: FAMILIES.PRODUCT, sport: null, product: "moonshot",
        era: ERAS.UNRECEIPTED_GAP, counts: {}, n: null,
        owner: ownerStamp, window: { from: gapFrom, to: gapTo },
        status: STATUSES.DISCLOSED_GAP,
        displayEligible: eligible("a disclosed gap — render as a gap, never as a number"),
        semantics: "Between the last June ledger row and the first receipt-era day no Moonshot owner carries an outcome. Not reconstructed.",
      }));
    }
  }

  /* LEDGER_ONLY — the June completed ladders, each its own cell; never merged with the protected record. */
  if (bankedLadders?.doc) {
    const bl = bankedLadders.doc;
    const stamp = { path: bankedLadders.path, generatedAt: strOrNull(bl.bankedAt), stampField: "bankedAt" };
    for (const l of bl.ladders ?? []) {
      const steps = Array.isArray(l.steps) ? l.steps : [];
      const won = steps.filter((s) => s.result === "won" || s.result === "win").length;
      const lost = steps.filter((s) => s.result === "lost" || s.result === "loss").length;
      const stepDates = steps.map((s) => s.date).filter((d) => DATE_RE.test(d ?? "")).sort();
      push(makeCell({
        recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product: "bank-builder",
        segment: `ladder-${l.ladder ?? steps.length}`,
        era: ERAS.LEDGER_ONLY, counts: { won, lost, pending: null, push: null, void: null },
        owner: stamp, window: { from: stepDates[0] ?? null, to: strOrNull(l.completedDate) ?? stepDates.at(-1) ?? null },
        status: STATUSES.FROZEN,
        displayEligible: eligible("a completed June ladder from the banked ledger — its own cell, labelled by ladder; never merged with the protected record or the receipt cycles"),
        semantics: `${l.label ?? "Completed ladder"}: steps are ledger events from the June operator process (multi-sport), not nightly receipts. W–L counts the ladder's steps. Settlement as the owner describes it: ${l.settlementSource ?? l.source ?? "official settlement (owner note)"}.`,
      }));
    }
    if (bl.historicalRecord && isInt(bl.historicalRecord.wins) && isInt(bl.historicalRecord.losses)) {
      push(makeCell({
        recordType: RECORD_TYPES.PRODUCT_RECORD, family: FAMILIES.PRODUCT, sport: null, product: "bank-builder",
        segment: `historical-record-${strOrNull(bl.bankedAt)?.slice(0, 10) ?? "banked"}`,
        era: ERAS.LEDGER_ONLY,
        counts: { won: bl.historicalRecord.wins, lost: bl.historicalRecord.losses, pending: intOrNull(bl.historicalRecord.pending), push: null, void: intOrNull(bl.historicalRecord.voids) },
        owner: stamp, window: { from: strOrNull(pf.startingDate), to: strOrNull(bl.bankedAt)?.slice(0, 10) ?? null },
        status: STATUSES.SUPERSEDED,
        displayEligible: ineligible("an earlier snapshot of the same population the July-7 protected base restates — superseded, kept for replay"),
        semantics: "banked-ladders.historicalRecord as of bankedAt. The protected base (PROTECTED_BASE) is the later snapshot of the same product; this one is never shown as a current figure.",
      }));
    }
  }
}

