#!/usr/bin/env node
/**
 * Write the exact legal drafts a reviewer approves, with the content hash the approval must carry.
 *
 *   node scripts/legal/export-legal-drafts.mjs
 *
 * Writes docs/legal/<id>-draft.md from lib/legal/texts.mjs. The hash printed in each file is the
 * value a counsel approval records in the content manifest; any later edit changes it, and the page
 * locks again until re-reviewed.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LEGAL_DOCUMENTS, LEGAL_PARAMETERS, legalContentHash, legalReadiness, renderLegal } from "../../src/lib/legal/texts.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, "..", "..", "..", "docs", "legal");
fs.mkdirSync(OUT, { recursive: true });
for (const id of Object.keys(LEGAL_DOCUMENTS)) {
  const r = renderLegal(id);
  const ready = legalReadiness(id);
  const params = [...new Set([...r.text.matchAll(/\[to be decided: (\w+)\]/g)].map((m) => m[1]))];
  const md = [
    `# ${r.title} — DRAFT FOR REVIEW · NOT LEGAL ADVICE`,
    "",
    "Generated from `app/src/lib/legal/texts.mjs` by `app/scripts/legal/export-legal-drafts.mjs`. Do not edit this file; edit the source and re-export.",
    "",
    `- Content hash (what an approval must record): \`${legalContentHash(id)}\``,
    `- Publishable now: **${ready.publishable ? "yes" : "no"}**`,
    ...ready.reasons.map((x) => `  - ${x}`),
    `- Undecided parameters: ${params.length ? params.join(", ") : "none"}`,
    `- Parameter sources: ${Object.entries(LEGAL_PARAMETERS).map(([k, v]) => `${k} — ${v.source}`).join("; ")}`,
    "",
    "---",
    "",
    ...r.sections.flatMap((s) => [`## ${s.heading}`, "", ...s.paragraphs.flatMap((p) => [p, ""])]),
  ].join("\n");
  fs.writeFileSync(path.join(OUT, `${id}-draft.md`), md);
  console.log(`[legal] wrote docs/legal/${id}-draft.md · hash ${legalContentHash(id).slice(0, 12)}… · publishable ${ready.publishable}`);
}
